import { InvalidTokenError, type TgUpdate } from "./telegram";

/**
 * Один проход опроса Telegram — и ЕДИНСТВЕННОЕ место, где рождается сигнал
 * «поллер жив» (круг починок среза A2, A-1).
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ МОДУЛЕМ. Раньше heartbeat писал независимый
 * `setInterval(...).unref()` рядом с циклом опроса. `.unref()` значит «не
 * удерживать процесс», но НЕ «не срабатывать»: пока процесс жив, таймер тикает.
 * А процесс живёт САМ ПО СЕБЕ — на `InvalidTokenError` бот печатает «БОТ НЕ
 * ЗАПУСТИЛСЯ» и навсегда уходит в `idle()`, который держит ref-таймер. Итог:
 * токен отозван в BotFather, ни одно сообщение не обрабатывается и не будет, а
 * панель приложений раз в пять минут получает свежий `bot.heartbeat` и пишет
 * «Telegram-бот · в порядке · бот отвечает: последний сигнал 2 мин назад». То
 * же и при устойчивом 409 (два поллера на одном токене): бесконечный retry
 * каждые 5 с без единого обновления — и зелёная строка. Это ровно тот отказ,
 * ради которого heartbeat заводили.
 *
 * Теперь сигнал привязан к ФАКТУ: Telegram ответил на `getUpdates`. Отдельный
 * таймер не нужен — дедуп по пятиминутному бакету (`clientKey` в
 * `heartbeat.ts`) делает запись идемпотентной, сколько бы витков ни прошло:
 * при `timeout` long polling'а в десятки секунд витков за бакет много, а строка
 * в журнале — одна.
 *
 * Функция вынесена из `index.ts`, потому что бесконечный цикл в `main()` не
 * проверить тестом, а «сигнал не уходит при отказе опроса» — как раз то, что
 * обязано быть закрыто ассертом.
 */
export type PollOutcome = "passed" | "failed" | "invalid_token";

export interface PollDeps {
  getUpdates: () => Promise<TgUpdate[]>;
  processUpdate: (u: TgUpdate) => Promise<void>;
  /**
   * Зовут ПОСЛЕ успешного ответа Telegram — и только тогда.
   *
   * До разбора пачки, а не после: подтверждаем сам факт прохода опроса.
   * Ошибки отдельных update'ов ловятся ниже и работой поллера не являются —
   * offset уже сдвинут, и следующая пачка придёт независимо от них.
   */
  onPass: () => void;
}

export async function pollOnce(deps: PollDeps): Promise<PollOutcome> {
  let updates: TgUpdate[];
  try {
    updates = await deps.getUpdates();
  } catch (err) {
    if (err instanceof InvalidTokenError) {
      // Неверный токен не «пройдёт сам»: вместо бесконечного потока одинаковых
      // ошибок говорим один раз понятно и ждём, пока значение исправят.
      console.error(`\nБОТ НЕ ЗАПУСТИЛСЯ: ${err.message}\n`);
      return "invalid_token";
    }
    console.error("Ошибка опроса Telegram:", err);
    return "failed";
  }
  deps.onPass();
  for (const u of updates) {
    try {
      await deps.processUpdate(u);
    } catch (err) {
      // Ошибку не выпускаем в цикл опроса: offset сдвигается уже при ПОЛУЧЕНИИ
      // пачки (`telegram.ts`), и упавший update — например, answerCallback на
      // устаревшую кнопку — иначе уносил бы с собой все необработанные соседние
      // сообщения той же пачки. Навсегда: Telegram повторно их не отдаст.
      console.error("Сообщение из пачки не обработано (пачка продолжена):", err);
    }
  }
  return "passed";
}
