/**
 * Панель «Приложения» (волна A2, R-A2-3; решения Р-3, Р-4, Р-6).
 *
 * Отвечает на один вопрос: что происходит с источниками — с теми, что ходят
 * наружу (OurVend, курс, Notion, Telegram, модели), и с внутренними
 * мониторами, которые читают только Core.
 *
 * ГЛАВНОЕ ПРАВИЛО ЭКРАНА: «не оценить» не похоже на «в порядке». Оценку даёт
 * Core одним маршрутом (`GET /apps/health`) — панель не повторяет правила и не
 * сочиняет вторых формулировок; её работа в том, чтобы третье состояние нельзя
 * было прочитать как первое. Ноль прогонов, выключенный монитор и
 * ненастроенный источник выглядят спокойно ровно до того дня, когда молчание
 * оказывается поломкой.
 *
 * ВРЕМЯ — ЧАСТЬ СОСТОЯНИЯ (срез Д1, Р-Д1-2 и Р-Д1-3). «В порядке» без отметки
 * проверки утверждает только «когда-то было хорошо», а «не оценить» без
 * давности не отличает новый источник от молчащего неделю. При этом у каждого
 * состояния СВОЙ вопрос о времени, и одна колонка на все три врала бы дважды —
 * разбор в `времяСостояния`.
 *
 * Тёмная тема — не отсюда: `/apps` числится в `CONSOLE_ROUTES` (`lib/theme.ts`),
 * атрибут ставят middleware (первый кадр) и `ThemeSync` (SPA-переход).
 */

/**
 * Вес слова «сломано» (Р-Д1-4).
 *
 * 600, А НЕ 700. IBM Plex Mono подключён локально в начертаниях 400/500/600
 * (`apps/cc/src/app/layout.tsx`), файла 700 в проекте нет — браузер
 * синтезировал бы его размазыванием, и на 11-пиксельной метке (`.led`,
 * `globals.css`) это читается ХУЖЕ, чем отсутствие выделения. Следующий автор
 * поставит 700 «как в дизайне», если не прочитает этой причины.
 *
 * ВЕС ЗАДАЁТСЯ ЗДЕСЬ, А НЕ ОБЩИМ ПРАВИЛОМ `.led.blocked` В `globals.css`:
 * тот же класс носят статусы навыков `draft` и `deprecated`
 * (`components/skills-deck.tsx`) и включённый тумблер паузы — «черновик»,
 * «в архиве» и «на паузе» набрались бы полужирным вместе со «сломано», хотя
 * поломкой не являются. У строк этой витрины общего контейнера с ними нет,
 * поэтому вес живёт на слове.
 *
 * Экраны агентов решают ту же задачу иначе и правильно для себя: слово «затык»
 * печатают ТРИ поверхности (плитка сетки, шапка карточки, строка списка
 * `/agents`), их общий контейнер — `.agled`, и правило там
 * `.agled .led.blocked`. «Затык» вес получает ЗАКОННО по Р-Д1-4 — это то же
 * «сломано» на оси занятости.
 * Один эффект двумя способами — цена того, что общего контейнера у ЭТОЙ
 * витрины с ними нет; если он появится, правило стоит свести в одно.
 */
const ВЕС_ПОЛОМКИ = 600;

export default async function AppsPage() {
  let health: AppsHealth;
  try {
    health = await core.appsHealth();
  } catch (err) {
    return <CoreDown detail={err instanceof CoreUnavailable ? err.detail : String(err)} />;
  }

  const все = [...health.outside, ...health.internal];
  const счёт = (state: HealthState): number => все.filter((r) => r.state === state).length;
  // Сводка печатает ВСЕ ТРИ числа, включая нули: «не оценить 0» — это ответ,
  // а спрятанный ноль читался бы как «таких строк не бывает».
  // Сводка берёт СЛОВА ИЗ ТОГО ЖЕ СЛОВАРЯ, что лампы строк ниже (ревью Ф-1):
  // до этого те же три слова стояли здесь литералами внутри одного длинного
  // шаблона — сторож второго словаря их не видит, а правка «не оценить» в
  // словаре развела бы заголовок экрана с его же строками. Текст не изменился
  // ни на байт.
  const сводка =
    `${HEALTH_WORD.ok} ${счёт("ok")} · ${HEALTH_WORD.bad} ${счёт("bad")}` +
    ` · ${HEALTH_WORD.unknown} ${счёт("unknown")}`;
  /*
   * Момент, от которого считается давность проверок.
   *
   * Часы ЯДРА (`health.now`), а не `Date.now()` браузера — тот же довод, что у
   * сетки агентов (`agent-grid.tsx`) и доски рутин (`lib/crons.ts`): на границе
   * суток «сегодня» панели и «сегодня» Core разъезжаются, и строка назвала бы
   * давность, которая не сходится с абсолютным временем в соседней строке того
   * же экрана.
   */
  const момент = new Date(health.now);

  return (
    <>
      <div className="page-head">
        <h1>Приложения</h1>
        <p className="lead">
          {все.length === 0
            ? `Core не назвал ни одного источника · собрано ${when(health.now)}`
            : `${сводка} · собрано ${when(health.now)}`}
        </p>
      </div>

      <HealthSection
        title="Снаружи"
        hint="Ходят в чужую систему: сбор OurVend, курс ЦБ, доставка в Notion, Telegram-бот, модели."
        rows={health.outside}
        now={момент}
        emptyTitle="Core не назвал ни одного источника снаружи"
        emptyHint="Ни сбор OurVend, ни курс, ни доставка, ни бот не отчитывались — проверь, запущен ли слой агентов."
      />
      <HealthSection
        title="Внутренние мониторы"
        hint="Сам слой агентов и мониторы, которые читают только Core: здоровье рантайма и данных, а не связи с чужой системой."
        rows={health.internal}
        now={момент}
        emptyTitle="Core не назвал ни одного внутреннего монитора"
        emptyHint="Снимка расписаний в Core нет — неизвестно даже, включены ли мониторы. Проверь слой агентов."
      />
    </>
  );
}

function HealthSection({
  title,
  hint,
  rows,
  now,
  emptyTitle,
  emptyHint,
}: {
  title: string;
  hint: string;
  rows: readonly AppsHealthRow[];
  /** Часы Core: давность строк считается от них, а не от часов браузера. */
  now: Date;
  emptyTitle: string;
  emptyHint: string;
}) {
  return (
    <section className="apps-section">
      <div className="section-title">{title}</div>
      <p className="hint">{hint}</p>
      {rows.length === 0 ? (
        <div className="empty">
          <b>{emptyTitle}</b>
          {emptyHint}
        </div>
      ) : (
        rows.map((row) => <HealthRowView key={row.key} row={row} now={now} />)
      )}
    </section>
  );
}

/**
 * Что печатает колонка времени (Р-Д1-2, Р-Д1-3; круг починок Ф-1 и Ф-4).
 *
 * У КАЖДОГО СОСТОЯНИЯ СВОЙ ВОПРОС О ВРЕМЕНИ, и общая формулировка на все три
 * соврала бы дважды:
 *
 * - «в порядке» отвечает «НАСКОЛЬКО ЭТО СВЕЖО» — давностью. Ради этого вопроса
 *   срез и затевался: утром на проде все девять источников стояли `ok`, и по
 *   экрану нельзя было отличить проверку двадцать минут назад от проверки
 *   двадцать часов назад. Абсолютный момент («проверено 6 сент., 14:30») этого
 *   не отвечает: владелец должен вычесть его из «собрано 7 сент., 11:40» в
 *   шапке — через границу суток, в уме, у САМОЙ ЧАСТОЙ строки экрана.
 *   Подсказкой (`title`) это не лечится: она не читается взглядом и не
 *   существует на телефоне.
 * - «не оценить» отвечает «давно ли молчим» — той же давностью, но своим
 *   глаголом: «проверяли» вместо «проверено». У зелёной строки проверка
 *   ПРОШЛА, здесь известно только, что её пытались сделать.
 * - «сломано» отвечает «КОГДА ИМЕННО СЛОМАЛОСЬ», и здесь абсолютный момент
 *   остаётся намеренно: следующий шаг владельца — журнал прогонов, логи,
 *   история деплоя, и туда несут время, а не давность. Подпись у него та же,
 *   что у зелёной: самая срочная строка экрана не имеет права быть
 *   единственной без подписи — голая цифра не говорит, про что она.
 *
 * ЧЕГО МОМЕНТ НЕ ЗНАЧИТ, РАЗБИРАЕТ `безМоментаПроверки`, а не эта функция:
 * `null` в `lastCheckedAt` — это два разных факта, и печатать их одним словом
 * значит утверждать о мире то, чего система не знает.
 *
 * `null` РАЗБИРАЕТСЯ ЗДЕСЬ, А НЕ В `ago()`. Хелпер принимает `string` и на
 * чужом входе не отказывает, а молча считает: `ago(null as never, now)` дало бы
 * «20703 дня назад» — число, которое выглядит измерением.
 */
function времяСостояния(row: AppsHealthRow, now: Date): string {
  switch (row.state) {
    case "ok":
      // `null` у зелёной строки — дефект провода (Core обязан знать момент
      // проверки у того, что проверил). Говорим об этом словами: прочерк
      // выглядел бы как «времени тут не бывает» и спрятал бы поломку контракта.
      return row.lastCheckedAt !== null
        ? `проверено ${ago(row.lastCheckedAt, now)}`
        : "проверка не датирована";
    case "unknown":
      // ПРЕДЛОГА «НАЗАД» ЗДЕСЬ НЕТ: `ago()` возвращает фразу целиком («4 дня
      // назад», «5 минут назад», «только что»), и дописанный предлог давал бы
      // «4 дня назад назад». Формулировка глаголом, а не «последняя проверка
      // …», ровно поэтому: она читается и на ветке «только что», у которой
      // предлога нет вовсе. Ловушку держит ассерт на одно «назад» в тесте.
      return row.lastCheckedAt === null
        ? безМоментаПроверки(row)
        : `проверяли ${ago(row.lastCheckedAt, now)}`;
    case "bad":
      /*
       * `at` ЗДЕСЬ НЕ ПЕЧАТАЕТСЯ, И ЭТО РЕШЕНИЕ, А НЕ УПРОЩЕНИЕ.
       * Поле у разных строк значит разные события: у сбора OurVend — последний
       * УСПЕХ, у очереди Notion — создание самой старой висящей доставки. Один
       * ярлык на все сочинил бы смысл, которого в поле нет, а без ярлыка это
       * голая цифра. Убрали второе, а не подписали первое.
       *
       * `null` ДОСТИЖИМ, вопреки виду («сломан — значит проверяли»): у строки
       * моделей вердикт `bad` выносится по КОНФИГУРАЦИИ, а не по прогону —
       * битый дневной потолок, отсутствие действующей цены, нулевой потолок
       * (`apps/core/src/apps/apps-health.ts`, `вердиктМоделей`). Все три
       * закрывают ledger, поэтому ни один вызов не завершается, и момента
       * проверки не появляется НИКОГДА — состояние самоподдерживающееся, а не
       * угловое.
       */
      return row.lastCheckedAt !== null
        ? `проверено ${when(row.lastCheckedAt)}`
        : безМоментаПроверки(row);
  }
}

/**
 * Момента проверки нет — ЧТО ИМЕННО об этом известно (круг починок, Ф-1).
 *
 * ДВА ФАКТА, А НЕ ОДИН, И ОНИ ПРОТИВОПОЛОЖНЫ. «Проверок не было ни разу» —
 * утверждение Core (`checksKnown: true`): журнал проверок прочитан, записей в
 * нём нет. «О проверках не известно» (`false`) — Core не смог прочитать журнал
 * либо проходы были, а момента у них нет.
 *
 * ДО ЭТОЙ ФУНКЦИИ ЭКРАН ПЕЧАТАЛ «не запускался» В ОБОИХ СЛУЧАЯХ, то есть
 * утверждал о мире то, чего система не знает: диспетчер Notion мог работать
 * год, а строка отправляла владельца искать несуществующую поломку. Строка
 * «здоровье не оценить: у закрытых доставок (3) нет момента закрытия ·
 * не запускался» противоречила себе в одной строке — права была левая половина.
 *
 * ФОРМУЛИРОВКА НЕЙТРАЛЬНАЯ И БЕЗ ЧИСЛА: «неизвестно» не должно читаться ни как
 * «проверок не было», ни как измерение. Причина при этом уже сказана рядом —
 * `summary` строки цитирует диагноз Core («источник не отвечает — оценить
 * нечем»), и колонка времени её не повторяет.
 */
function безМоментаПроверки(row: AppsHealthRow): string {
  return row.checksKnown ? "не запускался" : "когда проверяли — неизвестно";
}

/** Строка источника: состояние словом и весом, заголовок, причина, время, ссылка на починку. */
function HealthRowView({ row, now }: { row: AppsHealthRow; now: Date }) {
  const тело = (
    <>
      <span
        className={HEALTH_LED[row.state]}
        style={row.state === "bad" ? { fontWeight: ВЕС_ПОЛОМКИ } : undefined}
      >
        {HEALTH_WORD[row.state]}
      </span>
      <div className="ab">
        <div className="an">{row.title}</div>
        <div className="as">{row.summary}</div>
        {/* Цитата источника — текстом: итог прогона и ошибка доставки приходят
            из базы, и разметкой их рендерить нельзя. */}
        {row.detail !== undefined && <div className="hint">{row.detail}</div>}
      </div>
      <div className="aw">{времяСостояния(row, now)}</div>
    </>
  );
  return row.href !== undefined ? (
    <Link href={row.href} className="approw" data-state={row.state}>
      {тело}
    </Link>
  ) : (
    <div className="approw" data-state={row.state}>
      {тело}
    </div>
  );
}
