/**
 * Аватар агента: 8×8 клеток, детерминированно от имени.
 *
 * Имя рядом читается словами — картинка нужна, чтобы карточку одного агента
 * находить глазом в сетке, поэтому она `aria-hidden`.
 *
 * ОТДЕЛЬНЫМ КОМПОНЕНТОМ (волна A2, решение Р-7): рисунок обязан совпадать во
 * всех местах, где агента показывают, — витрина навыков, сетка на главной,
 * шапка карточки. Вторая копия FNV-1a разошлась бы с первой на первой же
 * правке, и один агент получил бы два лица.
 *
 * Размер задаёт место: базовый `.av8` — 16px, `.agtile .av8` — 26px. Своего
 * пропа размера нет намеренно: масштаб — вопрос раскладки, а не компонента.
 */
export function Av8({ name }: { name: string }) {
  // FNV-1a: стабильный и короткий — одно имя всегда даёт один и тот же рисунок.
  let hash = 2166136261;
  for (let i = 0; i < name.length; i += 1) {
    hash ^= name.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  const cells: { x: number; y: number }[] = [];
  for (let y = 0; y < 8; y += 1) {
    for (let x = 0; x < 4; x += 1) {
      if (((hash >>> (y * 4 + x)) & 1) === 1) {
        // Левую половину зеркалим — получается «лицо», а не случайный шум.
        cells.push({ x, y }, { x: 7 - x, y });
      }
    }
  }
  return (
    <span className="av8" aria-hidden="true">
      <svg viewBox="0 0 8 8" fill="currentColor">
        {cells.map((c) => (
          <rect key={`${c.x}-${c.y}`} x={c.x} y={c.y} width="1" height="1" />
        ))}
      </svg>
    </span>
  );
}
