"use client";

import { usePathname } from "next/navigation";
import { useLayoutEffect } from "react";
import { THEME_COOKIE, isConsoleRoute, themeFor } from "../lib/theme";

/**
 * Значение куки темы из `document.cookie` — простой разбор, без библиотек.
 *
 * Возвращается СЫРАЯ строка, а не `ThemeChoice`: что считать законным
 * значением, решает одна функция `themeFor` (общая с прокси, `apps/cc/src/proxy.ts`),
 * и второй проверки здесь быть не должно — иначе клиент и сервер разошлись бы
 * на первом же новом значении.
 *
 * ДЕКОДИРУЕТСЯ, а не отдаётся как есть (круг починок 1, находка 1): прокси
 * читает куку через `request.cookies.get(...).value`, который значение
 * декодирует, а `document.cookie` браузера — нет. Без декодирования здесь
 * «одно правило на двух входах» было бы ложью: кука `%64ark` («dark» в
 * процентной записи) сервер принял бы, а клиент после гидрации отверг
 * бы — та же форма Д-2 (разметка одно, эффект через кадр другое), другой
 * дверью. `decodeURIComponent` бросает на оборванном проценте — кука
 * подделываема кем угодно, и падать эффекту нельзя; в этом случае считаем
 * куку мусором (равносильно её отсутствию — `themeFor` отвергнет и сырую
 * строку тоже, ни одно легальное значение декодирования не требует).
 *
 * БЕРЁТСЯ ПОСЛЕДНЕЕ СОВПАДЕНИЕ, а не первое (круг починок 2): при ДВУХ куках
 * `mydon_theme` (разные `Path`/`Domain` — панель такого не пишет, но положить
 * может DevTools или другое приложение того же хоста: куки не различают порты)
 * сервер видит ПОСЛЕДНЮЮ — `RequestCookies` в Next кладёт пары в `Map`, и её
 * читают и прокси, и `cookies()` в корневом layout. Первое совпадение здесь
 * давало бы ту же асимметрию, что и отсутствие декодирования: разметка от
 * сервера одна, а эффект через кадр — другая.
 */
function кукаТемы(): string | undefined {
  const ключ = `${THEME_COOKIE}=`;
  let последнее: string | undefined;
  for (const часть of document.cookie.split(";")) {
    const пара = часть.trim();
    if (!пара.startsWith(ключ)) continue;
    const сырое = пара.slice(ключ.length);
    try {
      последнее = decodeURIComponent(сырое);
    } catch {
      последнее = сырое;
    }
  }
  return последнее;
}

/**
 * Тема при SPA-навигации (срез Д2, Р-Д2-4).
 *
 * Первый кадр держит сервер: прокси (`apps/cc/src/proxy.ts`) кладёт
 * `themeFor(...)` в заголовок, корневой layout ставит `data-theme` на
 * `<html>` и `data-console` на `.app` прямо в разметке. Но корневой layout
 * НЕ ПЕРЕРИСОВЫВАЕТСЯ при переходе между страницами — без этого компонента
 * `data-theme="dark"` с `/apps` остался бы на `/stock`. Поэтому при каждой
 * смене `pathname` те же два атрибута ставятся заново ТЕМ ЖЕ правилом
 * `themeFor`: модуль без серверных импортов, его читают и прокси, и клиент,
 * и правило у них одно.
 *
 * Cleanup'а («вернуть прежнее значение при размонтировании»), который был у
 * прежнего постраничного штампа темы (до Д2 он стоял на пяти страницах и
 * снимал `data-theme` при уходе с них), здесь НЕТ, и это не упущение:
 * компонент стоит в корневом layout один раз и не размонтируется, а нужное
 * значение ставит сам при каждой смене маршрута — восстанавливать нечего и
 * некому. Снимок «прежнего» к тому же врал бы после смены куки
 * переключателем: штамп при уходе со страницы затёр бы явный выбор
 * пользователя устаревшим снимком.
 *
 * `useLayoutEffect`, а не `useEffect`: атрибуты меняются до отрисовки нового
 * экрана, и кадра «новая страница в теме старой» нет. На сервере React 19
 * этот хук не выполняет и не предупреждает.
 */
export function ThemeSync() {
  const pathname = usePathname();

  useLayoutEffect(() => {
    const html = document.documentElement;
    const тема = themeFor(pathname, кукаТемы());
    /*
     * Пишем, только если значение реально меняется (круг починок 1, находка
     * 5). `setAttribute`/`removeAttribute` ставят запись мутации ДАЖЕ на то
     * же значение — DOM не сверяет старое с новым сам. `brain-graph.tsx`
     * слушает `data-theme` MutationObserver'ом ровно затем, чтобы
     * перерисовать холст, и без этой сверки переход между двумя тёмными
     * маршрутами (гидрация /apps, затем /apps → /crons) гонял бы
     * перерисовку без единой смены темы — сегодня спасает порядок
     * эффектов, но это цена, а не гарантия.
     */
    if ((html.dataset.theme ?? null) !== тема) {
      if (тема === null) delete html.dataset.theme;
      else html.dataset.theme = тема;
    }

    /*
     * `.app` МОЖЕТ ОТСУТСТВОВАТЬ В DOM (круг починок 1, находка 6) — сегодня
     * так рендерится сам компонент в изоляции (юнит-тест без обёртки), а
     * поиск по DOM вместо ссылки не даёт гарантии на будущее ни от одного
     * компилятора. Промолчать здесь — РЕШЕНИЕ, а не пропуск: `data-console`
     * это косметика сетки холста, и её отсутствие не должно ронять `data-
     * theme` выше, который от `.app` не зависит и уже поставлен.
     */
    const app = document.querySelector(".app");
    if (app instanceof HTMLElement) {
      if (isConsoleRoute(pathname)) app.dataset.console = "true";
      else delete app.dataset.console;
    }
  }, [pathname]);

  return null;
}
