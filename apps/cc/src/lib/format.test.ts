import { describe, expect, it } from "vitest";
import { ago, amount, count, money } from "./format";

/**
 * Сверка БАЙТА, а не вида. U+00A0 и обычный пробел на экране неотличимы —
 * ровно поэтому баг «скопированная из панели сумма не находится ни поиском по
 * странице, ни в боте» прожил до среза «Хвосты».
 */
describe("Форматтеры чисел панели (R-H-3)", () => {
  it("count() и amount() не содержат U+00A0 — эти числа копируют и сверяют", () => {
    expect(count(1_234_567)).not.toContain("\u00a0");
    expect(amount(1_234_567)).not.toContain("\u00a0");
    expect(count(1_234_567)).toBe("1 234 567");
  });

  it("money() U+00A0 СОХРАНЯЕТ: это решение R-H-3, а не забытая правка", () => {
    // Её зовут 42 раза, в основном в GLOBERENT и финансах, где число читают
    // глазами. Если этот тест однажды покраснеет «сам собой» — значит,
    // `money()` правили вместо листа, и сорок два чужих места поехали молча.
    expect(money(1_234_567)).toContain("\u00a0");
  });

  it("amount() — это money() без NBSP, а не второе правило округления", () => {
    expect(amount(1_234_567)).toBe(money(1_234_567).replace(/\u00a0/g, " "));
  });

  it("count() от мусора печатает «NaN», а не русское «не число» (ревью m8)", () => {
    // `count(Number(r.amount))` кормят строкой из БД (`sales-view.tsx`,
    // `supply-views.tsx`): колонки `numeric`, то есть на практике парсятся
    // всегда. Но раньше на этом пути стояла `money()` со своим
    // `Number.isFinite`, и при мусоре панель печатала исходное значение.
    // Без защиты `toLocaleString("ru-RU")` выдаёт «не число» — строку, которую
    // владелец прочитает как ЧАСТЬ ОТЧЁТА, а не как отказ разобрать данные.
    expect(count(Number("не сумма"))).toBe("NaN");
    expect(count(Number.POSITIVE_INFINITY)).toBe("Infinity");
    // Ноль и отрицательные — обычные числа, защита их не трогает. Минус тут
    // ОБЫЧНЫЙ дефис, а не типографский U+2212 из `percent()`: `count()` его
    // не переписывает, и тест пришпиливает то, что код делает, а не то, что
    // хотелось бы прочитать.
    expect(count(0)).toBe("0");
    expect(count(-1_234)).toBe("-1 234");
  });
});

/**
 * Границы `ago()` пришпилены к ФИКСИРОВАННОМУ `now`, а не к часам машины.
 * Ассерт «2 дня назад» от `Date.now()` покраснел бы сам через две недели —
 * ровно та ловушка, из-за которой у хелпера `now` параметром.
 */
describe("Давность одной фразой — ago() (срез Д1)", () => {
  const СЕЙЧАС = new Date("2026-09-07T12:00:00.000Z");
  /** Отметка, отстоящая от `СЕЙЧАС` назад на столько-то миллисекунд. */
  const назад = (ms: number): string => new Date(СЕЙЧАС.getTime() - ms).toISOString();

  it("свежую отметку числом не называет: «только что», а не «0 минут назад»", () => {
    expect(ago(назад(0), СЕЙЧАС)).toBe("только что");
    expect(ago(назад(59_999), СЕЙЧАС)).toBe("только что");
  });

  it("минуты: с 60-й секунды и до 59-й минуты, с русскими формами", () => {
    expect(ago(назад(60_000), СЕЙЧАС)).toBe("1 минуту назад");
    expect(ago(назад(2 * 60_000), СЕЙЧАС)).toBe("2 минуты назад");
    expect(ago(назад(5 * 60_000), СЕЙЧАС)).toBe("5 минут назад");
    // Второй десяток — отдельный ассерт: «21 минуту», а не «21 минут».
    expect(ago(назад(21 * 60_000), СЕЙЧАС)).toBe("21 минуту назад");
    expect(ago(назад(59 * 60_000 + 59_000), СЕЙЧАС)).toBe("59 минут назад");
  });

  it("часы: ровно с 60-й минуты и до 23:59", () => {
    expect(ago(назад(60 * 60_000), СЕЙЧАС)).toBe("1 час назад");
    expect(ago(назад(2 * 3_600_000), СЕЙЧАС)).toBe("2 часа назад");
    expect(ago(назад(5 * 3_600_000), СЕЙЧАС)).toBe("5 часов назад");
    expect(ago(назад(21 * 3_600_000), СЕЙЧАС)).toBe("21 час назад");
    expect(ago(назад(23 * 3_600_000 + 59 * 60_000), СЕЙЧАС)).toBe("23 часа назад");
  });

  it("дни: ровно с 24-го часа, и крупнее суток единиц нет", () => {
    expect(ago(назад(24 * 3_600_000), СЕЙЧАС)).toBe("1 день назад");
    expect(ago(назад(2 * 86_400_000), СЕЙЧАС)).toBe("2 дня назад");
    expect(ago(назад(11 * 86_400_000), СЕЙЧАС)).toBe("11 дней назад");
    expect(ago(назад(21 * 86_400_000), СЕЙЧАС)).toBe("21 день назад");
    // Недель и месяцев нет НАМЕРЕННО: «45 дней назад» владелец сравнивает с
    // порогом в уме, а «1 месяц назад» спрятал бы разницу между 31 и 59 днями.
    expect(ago(назад(45 * 86_400_000), СЕЙЧАС)).toBe("45 дней назад");
  });

  it("отметка из будущего — «только что», а не минус", () => {
    // Часы Core и момент снимка расходятся на секунды при любом запросе, и
    // «−1 минуту назад» — не фраза.
    expect(ago(назад(-90_000), СЕЙЧАС)).toBe("только что");
  });

  it("мусор вместо даты — прочерк, а не «NaN дней назад» (довод тот же, что у count())", () => {
    expect(ago("не дата", СЕЙЧАС)).toBe("—");
    expect(ago("", СЕЙЧАС)).toBe("—");
  });

  it("считает ОТ ПАРАМЕТРА, а не от часов машины", () => {
    // Этот ассерт и есть сторож требования: возьми функция `new Date()`
    // внутрь — здесь напечаталось бы «9000+ дней назад».
    expect(ago("2000-01-01T00:00:00.000Z", new Date("2000-01-01T03:00:00.000Z"))).toBe(
      "3 часа назад",
    );
  });
});
