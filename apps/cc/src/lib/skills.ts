import type { SkillDeckItem } from "./core";

/**
 * Навык есть чем исполнить: тело файла у модели или код в реестре агентов.
 *
 * `executor: code` без кода — строка каталога без исполнителя: кнопка была
 * активна, задача создавалась, а worker угадывал по заголовку СОСЕДНИЙ навык
 * (решение Р-6 витрины).
 *
 * ЭКСПОРТИРУЕТСЯ ради витрины навыков (круг починок, C-7): пилюля «не
 * реализован» в `skills-deck.tsx` считала это же выражение второй копией —
 * ровно тот дубль, который срез убирал. Одна правка правила обязана менять и
 * кнопку, и метку, иначе экран покажет активную кнопку рядом с меткой «не
 * реализован» (или наоборот).
 */
export function implemented(item: SkillDeckItem): boolean {
  return item.executor === "llm" || item.hasCode;
}

/**
 * Можно ли запустить навык прямо сейчас — и если нет, то что с этим делать.
 *
 * ОДНО ПРАВИЛО НА ВСЮ ПАНЕЛЬ (волна A2, R-A2-5): кнопка «Запустить» есть и на
 * витрине навыков, и в карточке агента, а Core отклоняет запуск навыка, не
 * закреплённого за агентом, и запуск у выключенного агента. Вторая копия
 * правила разошлась бы с первой, и один и тот же навык был бы «нельзя» на
 * одном экране и «можно» на другом.
 */
export function runnable(item: SkillDeckItem): { canRun: boolean; reason?: string } {
  if (!implemented(item)) {
    return { canRun: false, reason: "Навык ещё не реализован" };
  }
  if (item.agentStatus !== "active") return { canRun: false, reason: "Включи агента в его карточке" };
  if (!item.enabled) return { canRun: false, reason: "Впиши навык агенту в его карточке" };
  return { canRun: true };
}
