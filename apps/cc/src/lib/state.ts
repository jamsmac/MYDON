/**
 * НАСТРОЙКА СИСТЕМЫ (тумблеры пауз на доске рутин) → слово.
 *
 * Четвёртая ось, и она здесь не ради полноты: её «на паузе» — то же слово, что
 * у занятости агента (`AGENT_STATE_WORD.paused`), а значит другое: «выключено
 * настройкой сразу у всех», а не «этот агент отдыхает». Пока литерал жил в
 * тумблере, сторож второго словаря нёс бы исключение на файл, а исключения
 * гниют.
 *
 * Ключ — «включена ли пауза», поэтому `on` значит «стоим», а не «работаем».
 * Перепутанная полярность заставит тумблер врать про систему.
 */
export const PAUSE_WORD: Record<"on" | "off", string> = {
  on: "на паузе",
  off: "работают",
};

/**
 * Лампа тумблера — байт в байт то, что рисовал тернарник. Зелёная `led idle` у
 * «работают» — то же расхождение, что у пилюли карточки («зелёный = включён», а
 * не «зелёный = здоров»), и оно тоже долг Д2, а не правка этого среза.
 */
export const PAUSE_LED: Record<"on" | "off", string> = {
  on: "led blocked",
  off: "led idle",
};
