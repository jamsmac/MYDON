import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * ОДИН РАЗБОРЩИК CSS НА ВСЕХ СТОРОЖЕЙ ПАНЕЛИ (срез Д1).
 *
 * jsdom стилей не применяет, поэтому требования к оформлению сторожатся ПО
 * ИСХОДНИКУ `globals.css`: палитра состояний (`test/palette.test.ts`),
 * колоночность сетки агентов и вес слова «затык»
 * (`components/agent-grid.test.tsx`). Скобочный сканер тут был написан дважды —
 * третий экземпляр разошёлся бы с первыми двумя на первой же правке ровно так
 * же, как разъезжались словари состояний.
 *
 * Читать файл здесь, а не в каждом тесте, — та же причина: путь до
 * `app/globals.css` перестаёт быть строкой, повторённой в трёх местах.
 */

/** Объявляющее правило файла: условие охватывающего `@media`, селектор, тело. */
export type ПравилоCss = { контекст: string; селектор: string; тело: string };

/** Исходник таблицы стилей панели — один раз на прогон. */
export const стилиПанели: string = readFileSync(
  path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../app/globals.css"),
  "utf8",
);

/**
 * Правила файла скобочным сканером.
 *
 * Контекст обязателен и хранится ОТДЕЛЬНО от селектора. Во-первых, селектор
 * `:root:not([data-theme="light"])` сам по себе не говорит, что он внутри
 * медиавыражения, а вторая ветка тёмной темы отличается от первой ровно этим.
 * Во-вторых, склеенный с условием селектор нельзя сравнить с разметкой:
 * `element.matches("@media (min-width: 720px) .aggrid")` — не селектор.
 *
 * Заголовки самих `@media` тоже попадают в список (с телом из пробелов): их
 * объявления уже разобраны своими скобками, поэтому вызывающему достаточно
 * отфильтровать нужный селектор.
 */
export function правилаCss(source: string): ПравилоCss[] {
  const без = source.replace(/\/\*[\s\S]*?\*\//g, "");
  const собранные: ПравилоCss[] = [];
  const стек: string[] = [];
  let буфер = "";
  for (const ch of без) {
    if (ch === "{") {
      стек.push(буфер.trim());
      буфер = "";
    } else if (ch === "}") {
      const голова = стек.pop() ?? "";
      собранные.push({ контекст: стек.join(" "), селектор: голова, тело: буфер });
      буфер = "";
    } else буфер += ch;
  }
  return собранные;
}

/** Кастомные свойства в теле правила: имя → значение. */
export function токеныПравила(тело: string): Map<string, string> {
  const карта = new Map<string, string>();
  for (const m of тело.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;{}]+)/gi)) {
    карта.set(m[1] ?? "", (m[2] ?? "").trim());
  }
  return карта;
}

/** Блок палитры: имя для сообщений, условие охватывающего `@media`, селектор. */
export type Ветка = { имя: string; контекст: string; селектор: string };

/*
 * ТРИ БЛОКА ПАЛИТРЫ: светлая база и ДВЕ ветки тёмной темы (медиавыражение
 * ловит системную настройку, `[data-theme]` — явный выбор). Отдельными
 * константами, а не индексами массива: `ВЕТКИ[1]` в тесте ничего не называет.
 *
 * ЖИВУТ ЗДЕСЬ, А НЕ В СТОРОЖЕ ПАЛИТРЫ (круг починок среза Д1, Ф-2): к палитре
 * по веткам ходят уже два сторожа — сам сторож палитры и сторож навыка,
 * который сверяет напечатанные в `tokens.md` числа контраста с расчётом. Второй
 * экземпляр этого описания разошёлся бы с первым ровно так же, как разъезжались
 * словари состояний.
 */
export const СВЕТЛАЯ: Ветка = { имя: "светлая (:root)", контекст: "", селектор: ":root" };
export const ТЁМНАЯ_СИСТЕМНАЯ: Ветка = {
  имя: "тёмная системная (@media prefers-color-scheme: dark)",
  контекст: "@media (prefers-color-scheme: dark)",
  селектор: ':root:not([data-theme="light"])',
};
export const ТЁМНАЯ_ВЫБРАННАЯ: Ветка = {
  имя: 'тёмная выбранная (:root[data-theme="dark"])',
  контекст: "",
  селектор: ':root[data-theme="dark"]',
};
export const ВЕТКИ: readonly Ветка[] = [СВЕТЛАЯ, ТЁМНАЯ_СИСТЕМНАЯ, ТЁМНАЯ_ВЫБРАННАЯ];

/** Палитра одной ветки темы: имя токена → значение. Пустая карта — блока нет. */
export function палитраБлока(source: string, ветка: Ветка): Map<string, string> {
  const карта = new Map<string, string>();
  for (const r of правилаCss(source)) {
    if (r.контекст !== ветка.контекст || r.селектор !== ветка.селектор) continue;
    for (const [имя, значение] of токеныПравила(r.тело)) карта.set(имя, значение);
  }
  return карта;
}

/**
 * Классы, НЕСУЩИЕ СОСТОЯНИЕ: сама лампа и контейнеры, внутри которых стоит
 * слово состояния.
 *
 * КОНТЕЙНЕРЫ ЗДЕСЬ НЕ ДЛЯ ПОЛНОТЫ СПИСКА: `font-weight` НАСЛЕДУЕТСЯ, поэтому
 * правило на контейнере утяжеляет слово внутри ровно так же, как правило на
 * самой лампе, — а сторож искал подстроку `.led` и такого правила не видел
 * вовсе (девятый круг починок, 3.2). `run-led` в списке потому, что подстрокой
 * `.led` он НЕ ловится (`.run-led` — другой класс), а именно он носит пятое
 * значение оси занятости (`AGENT_BREAKDOWN_LED`).
 */
const НОСИТЕЛИ_СОСТОЯНИЯ: readonly string[] = ["led", "run-led", "agled", "approw"];

/** Имена классов в селекторе (без точки). */
function классыСелектора(селектор: string): string[] {
  return [...селектор.matchAll(/\.([a-zA-Z0-9_-]+)/g)].map((m) => m[1] ?? "");
}

/**
 * СУБЪЕКТ селектора — последний простой селектор после комбинаторов.
 *
 * Именно он говорит, ЧЕМУ правило задаёт свойство: у `.approw .an` субъект
 * `.an` (заголовок источника, не состояние), у `.agled .led.blocked` —
 * `.led.blocked`. Скобки считаются, иначе `[data-state="a b"]` разрезался бы
 * пробелом внутри значения.
 */
function субъектСелектора(селектор: string): string {
  let глубина = 0;
  let начало = 0;
  for (let i = 0; i < селектор.length; i += 1) {
    const ch = селектор[i] ?? "";
    if (ch === "[" || ch === "(") глубина += 1;
    else if (ch === "]" || ch === ")") глубина -= 1;
    else if (глубина === 0 && /[\s>+~]/.test(ch)) начало = i + 1;
  }
  return селектор.slice(начало).trim();
}

/**
 * ВЕС ЧИСЛОМ — ИЗ ЛЮБОЙ ЗАПИСИ `font-weight`, а не только из цифр.
 *
 * `bold` — ЭТО 700, и запрещённый 700 в такой записи проходил сторожа зелёным
 * (девятый круг починок, 3.1), обходя и Р-Д1-4, и весь довод про начертание,
 * которое браузер синтезирует размазыванием. Относительные ключевые слова
 * считаются от НОРМАЛЬНОГО начертания по таблице CSS (`bolder` → 700,
 * `lighter` → 100): точное значение зависит от унаследованного веса, но для
 * запрета важно, что слово тяжелее нормы, а не на сколько.
 */
export function весЧислом(значение: string): number | null {
  const текст = значение
    .replace(/!\s*important$/i, "")
    .trim()
    .toLowerCase();
  const КЛЮЧЕВЫЕ: Record<string, number> = { normal: 400, bold: 700, bolder: 700, lighter: 100 };
  const ключевое = КЛЮЧЕВЫЕ[текст];
  if (ключевое !== undefined) return ключевое;
  const число = Number.parseInt(текст, 10);
  return Number.isInteger(число) ? число : null;
}

/**
 * Правила, задающие НАЧЕРТАНИЕ слова состояния: `font-weight` там, где субъект
 * селектора — лампа или её контейнер.
 *
 * Живёт здесь, а не в тесте сетки агентов, потому что вес слова сторожат ДВА
 * теста с разных сторон: `components/agent-grid.test.tsx` — что «затык» его
 * получил, `test/state-weight.test.tsx` — что соседние поверхности не получили.
 * Второй экземпляр разбора разошёлся бы с первым, и одна из сторон замолчала бы.
 *
 * Селектор возвращается ПО ОДНОМУ на запятую, и отбор идёт ПО КАЖДОМУ: в
 * сообщении упавшего теста нужен ровно тот селектор, который дотянулся до
 * слова, а `.led.blocked, .an { font-weight: 600 }` не должен приносить `.an`.
 */
export function весаЛамп(source: string): { селектор: string; вес: number }[] {
  const итог: { селектор: string; вес: number }[] = [];
  for (const rule of правилаCss(source)) {
    for (const m of rule.тело.matchAll(/(?:^|[;\s])font-weight\s*:\s*([^;{}]+?)\s*(?=;|$)/gi)) {
      const вес = весЧислом(m[1] ?? "");
      if (вес === null) continue;
      for (const sel of rule.селектор.split(",")) {
        const один = sel.trim();
        const несёт = классыСелектора(субъектСелектора(один)).some((класс) =>
          НОСИТЕЛИ_СОСТОЯНИЯ.includes(класс),
        );
        if (несёт) итог.push({ селектор: один, вес });
      }
    }
  }
  return итог;
}

/**
 * ПОСЛЕДНЕЕ правило файла с этим селектором; `null` — такого нет.
 *
 * ПОСЛЕДНЕЕ, А НЕ ПЕРВОЕ (девятый круг починок, 3.3): при равной
 * специфичности браузер применяет то, что НИЖЕ по файлу, а оба сторожа
 * (палитры и навыка) читали первое — дубль правила ниже переопределял
 * проверенное значение молча. Условная обёртка (`@media`) тоже перекрывает —
 * в своих границах, — поэтому она из отбора не исключается: пусть сторож
 * покраснеет и человек посмотрит, чем молча одобрит правило, которого на
 * телефоне уже нет.
 */
export function последнееПравило(source: string, селектор: string): ПравилоCss | null {
  const все = правилаCss(source).filter((r) =>
    r.селектор.split(",").some((s) => s.trim() === селектор),
  );
  return все.at(-1) ?? null;
}

/**
 * ЧИСЛО КОНТРАСТА В КОММЕНТАРИИ — ЭТО УТВЕРЖДЕНИЕ, А НЕ ПОДПИСЬ.
 *
 * Ниже — расчёт контраста по WCAG и разбор объявлений ВМЕСТЕ С КОММЕНТАРИЕМ.
 * Живёт здесь, рядом с разборщиком: сторож палитры сверял число подстрокой
 * (`toContain("5,58")`), то есть проверял, что рядом с токеном стоит нужный
 * текст. Согласованно изменённая НЕВЕРНАЯ пара «значение + число» проходила
 * зелёной, и это не гипотеза: в срезе Д1 нашлось число «2,88:1», не совпадавшее
 * ни с одной из трёх поверхностей, — нашёл его человек пересчётом.
 *
 * `правилаCss` комментарии ВЫРЕЗАЕТ (иначе сканер спотыкался бы о скобки в
 * прозе), поэтому объявления с комментариями разбираются отдельно и построчно.
 */

/** Объявление токена вместе с комментарием, стоящим на ТОЙ ЖЕ строке. */
export type ОбъявлениеСКомментарием = {
  токен: string;
  значение: string;
  комментарий: string;
  /** Номер строки в файле — чтобы упавший сторож называл место, а не токен. */
  строка: number;
};

/**
 * Объявления кастомных свойств, у которых на строке есть комментарий.
 *
 * Построчно, а не по телу правила: комментарий привязан именно к строке
 * («число относится к ЭТОМУ значению»), и в теле правила эта привязка теряется.
 */
export function объявленияСКомментарием(source: string): ОбъявлениеСКомментарием[] {
  const итог: ОбъявлениеСКомментарием[] = [];
  const строки = source.split("\n");
  for (let i = 0; i < строки.length; i += 1) {
    const m = /^\s*(--[a-z0-9-]+)\s*:\s*([^;{}]+);\s*\/\*(.*?)\*\//i.exec(строки[i] ?? "");
    if (m === null) continue;
    итог.push({
      токен: m[1] ?? "",
      значение: (m[2] ?? "").trim(),
      комментарий: (m[3] ?? "").trim(),
      строка: i + 1,
    });
  }
  return итог;
}

/** Цвет `#rgb`/`#rrggbb` в каналы 0…255; иначе `null` — считать нечего. */
function каналы(цвет: string): [number, number, number] | null {
  const m = /^#([0-9a-f]{3}|[0-9a-f]{6})$/.exec(цвет.trim().toLowerCase());
  if (m === null) return null;
  const цифры = m[1] ?? "";
  const канал = (номер: number): number =>
    цифры.length === 3
      ? Number.parseInt((цифры[номер] ?? "0").repeat(2), 16)
      : Number.parseInt(цифры.slice(номер * 2, номер * 2 + 2), 16);
  return [канал(0), канал(1), канал(2)];
}

/**
 * Относительная яркость по WCAG 2 (§ relative luminance): канал линеаризуется
 * (порог 0,04045, гамма 2,4), дальше веса 0,2126 / 0,7152 / 0,0722.
 *
 * Формула переписана здесь ЦЕЛИКОМ и намеренно: сторож обязан считать сам, а не
 * спрашивать библиотеку, иначе «проверено» снова означало бы «совпало с тем же
 * источником, из которого число и взяли».
 */
function яркость(цвет: string): number | null {
  const rgb = каналы(цвет);
  if (rgb === null) return null;
  const линейный = (канал: number): number => {
    const s = канал / 255;
    return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * линейный(rgb[0]) + 0.7152 * линейный(rgb[1]) + 0.0722 * линейный(rgb[2]);
}

/**
 * Контраст двух цветов по WCAG: `(светлее + 0,05) / (темнее + 0,05)`.
 * `null` — хотя бы один цвет не разобрался (не hex): считать нечего.
 */
export function контраст(a: string, b: string): number | null {
  const x = яркость(a);
  const y = яркость(b);
  if (x === null || y === null) return null;
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
}
