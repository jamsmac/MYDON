import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * ОДИН РАЗБОРЩИК CSS НА ВСЕХ СТОРОЖЕЙ ПАНЕЛИ (срез Д1).
 *
 * jsdom стилей не применяет, поэтому требования к оформлению сторожатся ПО
 * ИСХОДНИКУ `globals.css`: палитра состояний (`test/palette.test.ts`),
 * колоночность сетки агентов и вес слова «затык»
 * (`components/agent-grid.test.tsx`). Скобочный сканер тут был написан дважды —
 * третий экземпляр разошёлся бы с первыми двумя на первой же правке ровно так
 * же, как разъезжались словари состояний.
 *
 * Читать файл здесь, а не в каждом тесте, — та же причина: путь до
 * `app/globals.css` перестаёт быть строкой, повторённой в трёх местах.
 */

/** Объявляющее правило файла: условие охватывающего `@media`, селектор, тело. */
export type ПравилоCss = { контекст: string; селектор: string; тело: string };

/** Исходник таблицы стилей панели — один раз на прогон. */
export const стилиПанели: string = readFileSync(
  path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../app/globals.css"),
  "utf8",
);

/**
 * Правила файла скобочным сканером.
 *
 * Контекст обязателен и хранится ОТДЕЛЬНО от селектора. Во-первых, селектор
 * `:root:not([data-theme="light"])` сам по себе не говорит, что он внутри
 * медиавыражения, а вторая ветка тёмной темы отличается от первой ровно этим.
 * Во-вторых, склеенный с условием селектор нельзя сравнить с разметкой:
 * `element.matches("@media (min-width: 720px) .aggrid")` — не селектор.
 *
 * Заголовки самих `@media` тоже попадают в список (с телом из пробелов): их
 * объявления уже разобраны своими скобками, поэтому вызывающему достаточно
 * отфильтровать нужный селектор.
 */
export function правилаCss(source: string): ПравилоCss[] {
  const без = source.replace(/\/\*[\s\S]*?\*\//g, "");
  const собранные: ПравилоCss[] = [];
  const стек: string[] = [];
  let буфер = "";
  for (const ch of без) {
    if (ch === "{") {
      стек.push(буфер.trim());
      буфер = "";
    } else if (ch === "}") {
      const голова = стек.pop() ?? "";
      собранные.push({ контекст: стек.join(" "), селектор: голова, тело: буфер });
      буфер = "";
    } else буфер += ch;
  }
  return собранные;
}

/** Кастомные свойства в теле правила: имя → значение. */
export function токеныПравила(тело: string): Map<string, string> {
  const карта = new Map<string, string>();
  for (const m of тело.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;{}]+)/gi)) {
    карта.set(m[1] ?? "", (m[2] ?? "").trim());
  }
  return карта;
}

/** Блок палитры: имя для сообщений, условие охватывающего `@media`, селектор. */
export type Ветка = { имя: string; контекст: string; селектор: string };

/*
 * ТРИ БЛОКА ПАЛИТРЫ: светлая база и ДВЕ ветки тёмной темы (медиавыражение
 * ловит системную настройку, `[data-theme]` — явный выбор). Отдельными
 * константами, а не индексами массива: `ВЕТКИ[1]` в тесте ничего не называет.
 *
 * ЖИВУТ ЗДЕСЬ, А НЕ В СТОРОЖЕ ПАЛИТРЫ (круг починок среза Д1, Ф-2): к палитре
 * по веткам ходят уже два сторожа — сам сторож палитры и сторож навыка,
 * который сверяет напечатанные в `tokens.md` числа контраста с расчётом. Второй
 * экземпляр этого описания разошёлся бы с первым ровно так же, как разъезжались
 * словари состояний.
 */
export const СВЕТЛАЯ: Ветка = { имя: "светлая (:root)", контекст: "", селектор: ":root" };
export const ТЁМНАЯ_СИСТЕМНАЯ: Ветка = {
  имя: "тёмная системная (@media prefers-color-scheme: dark)",
  контекст: "@media (prefers-color-scheme: dark)",
  селектор: ':root:not([data-theme="light"])',
};
export const ТЁМНАЯ_ВЫБРАННАЯ: Ветка = {
  имя: 'тёмная выбранная (:root[data-theme="dark"])',
  контекст: "",
  селектор: ':root[data-theme="dark"]',
};
export const ВЕТКИ: readonly Ветка[] = [СВЕТЛАЯ, ТЁМНАЯ_СИСТЕМНАЯ, ТЁМНАЯ_ВЫБРАННАЯ];

/** Палитра одной ветки темы: имя токена → значение. Пустая карта — блока нет. */
export function палитраБлока(source: string, ветка: Ветка): Map<string, string> {
  const карта = new Map<string, string>();
  for (const r of правилаCss(source)) {
    if (r.контекст !== ветка.контекст || r.селектор !== ветка.селектор) continue;
    for (const [имя, значение] of токеныПравила(r.тело)) карта.set(имя, значение);
  }
  return карта;
}

/**
 * Классы, НЕСУЩИЕ СОСТОЯНИЕ: сама лампа и контейнеры, внутри которых стоит
 * слово состояния.
 *
 * КОНТЕЙНЕРЫ ЗДЕСЬ НЕ ДЛЯ ПОЛНОТЫ СПИСКА: `font-weight` НАСЛЕДУЕТСЯ, поэтому
 * правило на контейнере утяжеляет слово внутри ровно так же, как правило на
 * самой лампе, — а сторож искал подстроку `.led` и такого правила не видел
 * вовсе (девятый круг починок, 3.2). `run-led` в списке потому, что подстрокой
 * `.led` он НЕ ловится (`.run-led` — другой класс), а именно он носит пятое
 * значение оси занятости (`AGENT_BREAKDOWN_LED`).
 */
const НОСИТЕЛИ_СОСТОЯНИЯ: readonly string[] = ["led", "run-led", "agled", "approw"];

/** Имена классов в селекторе (без точки). */
function классыСелектора(селектор: string): string[] {
  return [...селектор.matchAll(/\.([a-zA-Z0-9_-]+)/g)].map((m) => m[1] ?? "");
}

/**
 * СУБЪЕКТ селектора — последний простой селектор после комбинаторов.
 *
 * Именно он говорит, ЧЕМУ правило задаёт свойство: у `.approw .an` субъект
 * `.an` (заголовок источника, не состояние), у `.agled .led.blocked` —
 * `.led.blocked`. Скобки считаются, иначе `[data-state="a b"]` разрезался бы
 * пробелом внутри значения.
 */
function субъектСелектора(селектор: string): string {
  let глубина = 0;
  let начало = 0;
  for (let i = 0; i < селектор.length; i += 1) {
    const ch = селектор[i] ?? "";
    if (ch === "[" || ch === "(") глубина += 1;
    else if (ch === "]" || ch === ")") глубина -= 1;
    else if (глубина === 0 && /[\s>+~]/.test(ch)) начало = i + 1;
  }
  return селектор.slice(начало).trim();
}

/**
 * ВЕС ЧИСЛОМ — ИЗ ЛЮБОЙ ЗАПИСИ `font-weight`, а не только из цифр.
 *
 * `bold` — ЭТО 700, и запрещённый 700 в такой записи проходил сторожа зелёным
 * (девятый круг починок, 3.1), обходя и Р-Д1-4, и весь довод про начертание,
 * которое браузер синтезирует размазыванием. Относительные ключевые слова
 * считаются от НОРМАЛЬНОГО начертания по таблице CSS (`bolder` → 700,
 * `lighter` → 100): точное значение зависит от унаследованного веса, но для
 * запрета важно, что слово тяжелее нормы, а не на сколько.
 *
 * `null` — ЗАПИСЬ, КОТОРУЮ СТОРОЖ ПРОЧИТАТЬ НЕ МОЖЕТ (`var(--x)`, `inherit`,
 * опечатка). Это не «веса нет», а «вес неизвестен», и вызывающий обязан
 * отличать одно от другого: `весаЛамп` такую запись НЕ выбрасывает, а отдаёт с
 * `вес: null` — красным флагом (десятый круг починок, Ф-3).
 */
export function весЧислом(значение: string): number | null {
  const текст = значение
    .replace(/!\s*important$/i, "")
    .trim()
    .toLowerCase();
  const КЛЮЧЕВЫЕ: Record<string, number> = { normal: 400, bold: 700, bolder: 700, lighter: 100 };
  const ключевое = КЛЮЧЕВЫЕ[текст];
  if (ключевое !== undefined) return ключевое;
  if (!/^\d+$/.test(текст)) return null;
  const число = Number.parseInt(текст, 10);
  return Number.isInteger(число) ? число : null;
}

/** Объявление веса в теле правила: как записано и что из этого прочиталось. */
export type ОбъявлениеВеса = { запись: string; вес: number | null };

/** Ключевые слова, при которых `font:` НЕ несёт своего веса: наследование и системные шрифты. */
const ШОРТХЕНД_БЕЗ_ВЕСА =
  /^(inherit|initial|unset|revert|revert-layer|caption|icon|menu|message-box|small-caption|status-bar)$/i;

/**
 * Объявления веса в теле правила — из `font-weight` И ИЗ ШОРТХЕНДА `font:`.
 *
 * ШОРТХЕНД БЫЛ СЛЕПОЙ ЗОНОЙ (десятый круг починок, Ф-3): `font: 700 13px/1.2
 * var(--fm)` задаёт вес ровно так же, как `font-weight: 700`, а сторож искал
 * только второе. В шортхенде вес — один из необязательных токенов ПЕРЕД
 * размером (`[style] [variant] [weight] [stretch] size[/line-height] family`),
 * поэтому разбор берёт токены до первого, похожего на размер, и ищет среди них
 * число или ключевое слово веса. `font: inherit` и системные шрифты своего
 * веса не несут и пропускаются; `var()` среди токенов до размера — вес
 * неизвестен, и это `null`, а не пропуск.
 *
 * Шортхенд БЕЗ токена веса сбрасывает вес в `normal` — это тоже правда CSS, но
 * сторожу веса ламп она не нужна: сброс до нормы слово не утяжеляет, а список
 * «правил веса» из-за каждого `font: 13px …` разросся бы до бессмыслицы.
 */
export function объявленияВеса(тело: string): ОбъявлениеВеса[] {
  const итог: ОбъявлениеВеса[] = [];
  for (const m of тело.matchAll(/(?:^|[;\s])font-weight\s*:\s*([^;{}]+?)\s*(?=;|$)/gi)) {
    const запись = (m[1] ?? "").trim();
    итог.push({ запись, вес: весЧислом(запись) });
  }
  for (const m of тело.matchAll(/(?:^|[;\s])font\s*:\s*([^;{}]+?)\s*(?=;|$)/gi)) {
    const запись = (m[1] ?? "").replace(/!\s*important$/i, "").trim();
    if (ШОРТХЕНД_БЕЗ_ВЕСА.test(запись)) continue;
    const токены = запись.split(/\s+/);
    const размер = токены.findIndex(
      (т) =>
        /^[\d.]+(px|em|rem|%|pt|vw|vh|ch)(\/|$)/i.test(т) ||
        /^(xx-small|x-small|small|medium|large|x-large|xx-large|smaller|larger)(\/|$)/i.test(т),
    );
    const доРазмера = размер === -1 ? токены : токены.slice(0, размер);
    if (доРазмера.some((т) => /var\(/i.test(т))) {
      итог.push({ запись: `font: ${запись}`, вес: null });
      continue;
    }
    const весовой = доРазмера.find((т) => весЧислом(т) !== null && !/^normal$/i.test(т));
    if (весовой !== undefined) итог.push({ запись: `font: ${запись}`, вес: весЧислом(весовой) });
  }
  return итог;
}

/** Правило веса: селектор (по одному на запятую), вес и запись, из которой он прочитан. */
export type ПравилоВеса = { селектор: string; вес: number | null; запись: string };

/**
 * ВСЕ правила файла, задающие вес, — по одному селектору на запятую, без
 * отбора по субъекту (десятый круг починок, Ф-3).
 *
 * ДЛЯ НЕГАТИВНЫХ СТОРОЖЕЙ НУЖЕН ИМЕННО ПОЛНЫЙ СПИСОК: `font-weight`
 * наследуется от ЛЮБОГО предка, а не только от четырёх названных носителей, и
 * правило `.agtile { font-weight: 700 }` утяжеляло бы все слова сетки, оставаясь
 * невидимым для списка `весаЛамп` — мутация проходила зелёной. Проверка идёт
 * через `closest`, поэтому лишние правила в списке ничего не стоят: те, что до
 * слова не дотягиваются, просто не совпадут.
 *
 * Псевдоэлементы (`::before`, `::after`) исключены: их вес красит СГЕНЕРИРОВАННОЕ
 * содержимое, а не слово, и `closest` с таким селектором не про наследование.
 */
export function правилаВеса(source: string): ПравилоВеса[] {
  const итог: ПравилоВеса[] = [];
  for (const rule of правилаCss(source)) {
    for (const { запись, вес } of объявленияВеса(rule.тело)) {
      for (const sel of rule.селектор.split(",")) {
        const один = sel.trim();
        if (один === "" || один.startsWith("@") || /::/.test(субъектСелектора(один))) continue;
        итог.push({ селектор: один, вес, запись });
      }
    }
  }
  return итог;
}

/**
 * Правила, задающие НАЧЕРТАНИЕ слова состояния: вес там, где субъект
 * селектора — лампа или её контейнер.
 *
 * Живёт здесь, а не в тесте сетки агентов, потому что вес слова сторожат ДВА
 * теста с разных сторон: `components/agent-grid.test.tsx` — что «затык» его
 * получил, `test/state-weight.test.tsx` — что соседние поверхности не получили.
 * Второй экземпляр разбора разошёлся бы с первым, и одна из сторон замолчала бы.
 *
 * ОТБОР ПО НОСИТЕЛЯМ — ТОЛЬКО ДЛЯ ПОЗИТИВНОГО ВОПРОСА («какое правило даёт вес
 * затыку»). Негативные сторожа спрашивают `правилаВеса` без отбора: предок,
 * которого нет в списке носителей, утяжеляет слово ровно так же.
 *
 * `вес: null` ОТДАЁТСЯ, А НЕ ПРОПУСКАЕТСЯ: вес лампы через `var(--x)` или
 * запись, которую сторож не прочёл, — это правило, которое сторож не может ни
 * одобрить, ни отвергнуть. Раньше оно молча выпадало из списка, и лампа с весом
 * через переменную выглядела лампой без веса.
 *
 * Селектор возвращается ПО ОДНОМУ на запятую, и отбор идёт ПО КАЖДОМУ: в
 * сообщении упавшего теста нужен ровно тот селектор, который дотянулся до
 * слова, а `.led.blocked, .an { font-weight: 600 }` не должен приносить `.an`.
 */
export function весаЛамп(source: string): ПравилоВеса[] {
  return правилаВеса(source).filter((r) =>
    классыСелектора(субъектСелектора(r.селектор)).some((класс) =>
      НОСИТЕЛИ_СОСТОЯНИЯ.includes(класс),
    ),
  );
}

/**
 * ПОСЛЕДНЕЕ правило файла с этим селектором; `null` — такого нет.
 *
 * ПОСЛЕДНЕЕ, А НЕ ПЕРВОЕ (девятый круг починок, 3.3): при равной
 * специфичности браузер применяет то, что НИЖЕ по файлу, а оба сторожа
 * (палитры и навыка) читали первое — дубль правила ниже переопределял
 * проверенное значение молча. Условная обёртка (`@media`) тоже перекрывает —
 * в своих границах, — поэтому она из отбора не исключается: пусть сторож
 * покраснеет и человек посмотрит, чем молча одобрит правило, которого на
 * телефоне уже нет.
 *
 * ОГРАНИЧЕНИЕ, НАЗВАННОЕ ЧЕСТНО (десятый круг починок, Ф-3): это последнее
 * правило С ТЕМ ЖЕ СЕЛЕКТОРОМ, а не последнее ПРИМЕНИМОЕ. О специфичности
 * функция не знает: `.approw .led.unknown { color: … }` перекрыло бы
 * `.led.unknown { color: … }` в браузере при любом порядке в файле, а сторож
 * судил бы по перекрытому. Считать специфичность здесь — писать каскад
 * заново; вместо этого файл держит запрет: у субъекта `.led.<состояние>` ни
 * одно свойство лампы не задаётся ДВУМЯ РАЗНЫМИ селекторами из тех, что
 * целятся в тот же элемент и не слабее его по специфичности (`спорыЗаЛампу`,
 * ассерт в `palette.test.ts`; в одиннадцатом круге починок запрет расширен —
 * до него он сравнивал ТЕКСТ компаунда и не видел ни `.approw .led`, ни
 * `.led.unknown.hot`, ни `span.led.unknown`).
 */
export function последнееПравило(source: string, селектор: string): ПравилоCss | null {
  const все = правилаCss(source).filter((r) =>
    r.селектор.split(",").some((s) => s.trim() === селектор),
  );
  return все.at(-1) ?? null;
}

/** Спор за свойство лампы: один субъект `.led.<состояние>`, одно свойство, разные селекторы. */
export type СпорЗаЛампу = { субъект: string; свойство: string; селекторы: string[] };

/**
 * СПЕЦИФИЧНОСТЬ СЕЛЕКТОРА ТРОЙКОЙ (id, классы, элементы) — ГРУБО И НАРОЧНО В
 * СТОРОНУ ГРОМКОГО.
 *
 * Нужна ровно для сравнения «может ли ЭТО правило перекрыть проверенное», а у
 * сторожа две ошибки не равны: занизить вес соперника — промолчать о настоящем
 * перекрытии (тихий зелёный), завысить — позвать человека посмотреть. Поэтому
 * считается щедро: `:not(.a)` даёт и псевдокласс, и класс внутри (2 вместо 1
 * по стандарту), `:is()`/`:where()` не разбираются вовсе. Красный от такой
 * щедрости чинится переписыванием селектора, зелёный от занижения не чинится
 * никак — его не видно.
 *
 * `::before` весит как элемент (третий разряд), `[attr]` и псевдоклассы — как
 * класс (второй): это и есть правило CSS о специфичности.
 */
export function специфичность(селектор: string): [number, number, number] {
  const псевдоэлементов = (селектор.match(/::[a-zA-Z-]+/g) ?? []).length;
  const без = селектор.replace(/::[a-zA-Z-]+/g, " ");
  const ид = (без.match(/#[\w-]+/g) ?? []).length;
  const классов =
    (без.match(/\.[\w-]+/g) ?? []).length +
    (без.match(/\[[^\]]*\]/g) ?? []).length +
    (без.match(/:[a-zA-Z-]+/g) ?? []).length;
  const тегов = (
    без.replace(/#[\w-]+|\.[\w-]+|\[[^\]]*\]|:[a-zA-Z-]+/g, " ").match(/[a-zA-Z][\w-]*/g) ?? []
  ).length;
  return [ид, классов, тегов + псевдоэлементов];
}

/** `a` не слабее `b`: сравнение тройками, разряд за разрядом. */
function неСлабее(a: readonly [number, number, number], b: readonly [number, number, number]): boolean {
  for (let i = 0; i < 3; i += 1) {
    const x = a[i] ?? 0;
    const y = b[i] ?? 0;
    if (x !== y) return x > y;
  }
  return true;
}

/**
 * Свойства ламп, за которые СПОРЯТ РАЗНЫЕ СЕЛЕКТОРЫ, — то, что делает
 * `последнееПравило` слепым.
 *
 * Субъект лампы — компаунд с классом `led` и хотя бы одним классом состояния
 * (`.led.unknown`, `.led.blocked`), без псевдоэлемента: `::before` — другой
 * ящик, и его свойства с лампой не спорят. Сторожей спрашивают именно об этом
 * компаунде (`последнееПравило(css, ".led.unknown")`), поэтому и специфичность
 * сравнивается с его собственной.
 *
 * ЗАПРЕТ БЫЛ УЖЕ ДЫРЫ, КОТОРУЮ ЗАКРЫВАЕТ (одиннадцатый круг починок, М-3).
 * Прежняя редакция считала спором только правила, чей субъект — РОВНО ТОТ ЖЕ
 * текст компаунда, и мимо неё проходили три перекрытия, все реальные в
 * браузере:
 *   • `.approw .led { color }` против `.led.unknown { color }` — специфичность
 *     РАВНАЯ (0,2,0), победит то, что ниже по файлу, а субъект `.led` в старый
 *     отбор не попадал вовсе (один класс);
 *   • `.led.unknown.hot { color }` — компаунд ШИРЕ, ключ другой, спора нет;
 *   • `span.led.unknown { color }` — те же классы плюс тег, ключ другой.
 *
 * Теперь спорит ЛЮБОЕ правило, которое (а) целится в тот же элемент — субъект
 * несёт класс `led`, а набор его классов сравним с набором лампы
 * (подмножество или надмножество), и (б) не слабее лампы по специфичности.
 * Первая половина (а) обязательна целиком: без класса `led` под «подмножество»
 * попал бы любой бесклассовый субъект файла (`.tabbar a[aria-current]`) —
 * пустое множество вложено во всё.
 *
 * `.led { color }` (0,1,0) спором НЕ считается: он слабее `.led.unknown`
 * (0,2,0) при любом порядке в файле. `.agled .led.blocked { font-weight }` тоже
 * не спор — вес у этого субъекта задаёт только оно, а `.led.blocked { color }`
 * про другое свойство.
 */
export function спорыЗаЛампу(source: string, свойства: readonly string[]): СпорЗаЛампу[] {
  const объявляющие: { селектор: string; классы: string[]; вес: [number, number, number]; тело: string }[] = [];
  for (const rule of правилаCss(source)) {
    for (const sel of rule.селектор.split(",")) {
      const один = sel.trim();
      if (один === "" || один.startsWith("@")) continue;
      const субъект = субъектСелектора(один);
      if (/::/.test(субъект)) continue;
      объявляющие.push({
        селектор: один,
        классы: классыСелектора(субъект),
        вес: специфичность(один),
        тело: rule.тело,
      });
    }
  }
  // Субъекты ламп — в порядке появления в файле: сообщение упавшего сторожа
  // должно читаться сверху вниз, как сам файл.
  const лампы: string[] = [];
  for (const rule of правилаCss(source)) {
    for (const sel of rule.селектор.split(",")) {
      const субъект = субъектСелектора(sel.trim());
      if (/::/.test(субъект)) continue;
      const классы = классыСелектора(субъект);
      if (!классы.includes("led") || классы.length < 2) continue;
      if (!лампы.includes(субъект)) лампы.push(субъект);
    }
  }

  const споры: СпорЗаЛампу[] = [];
  for (const лампа of лампы) {
    const классыЛампы = классыСелектора(лампа);
    const весЛампы = специфичность(лампа);
    for (const свойство of свойства) {
      const объявлено = new RegExp(`(?:^|[;\\s])${свойство}\\s*:`, "i");
      const селекторы: string[] = [];
      for (const r of объявляющие) {
        if (!объявлено.test(r.тело)) continue;
        // САМА ЛАМПА В СУБЪЕКТЕ — ПЕРВОЕ УСЛОВИЕ. Без него в спор попадал бы
        // любой селектор файла с достаточным весом: у `.tabbar a[aria-current]`
        // классов в субъекте нет вовсе, и проверка «набор классов вложен»
        // проходила бы ПУСТЫМ множеством. К лампе такое правило отношения не
        // имеет — оно красит другой элемент.
        if (!r.классы.includes("led")) continue;
        // Целится ли правило в ТОТ ЖЕ элемент: узкий компаунд (`.led`) матчит
        // лампу, широкий (`.led.unknown.hot`) — её же с лишним классом; а
        // `.led.idle` против `.led.unknown` не сравним ни в ту, ни в другую
        // сторону и спором не является.
        const шире = классыЛампы.every((к) => r.классы.includes(к));
        const уже = r.классы.every((к) => классыЛампы.includes(к));
        if (!шире && !уже) continue;
        if (!неСлабее(r.вес, весЛампы)) continue;
        if (!селекторы.includes(r.селектор)) селекторы.push(r.селектор);
      }
      if (селекторы.length > 1) споры.push({ субъект: лампа, свойство, селекторы });
    }
  }
  return споры;
}

/**
 * ЧИСЛО КОНТРАСТА В КОММЕНТАРИИ — ЭТО УТВЕРЖДЕНИЕ, А НЕ ПОДПИСЬ.
 *
 * Ниже — расчёт контраста по WCAG и разбор объявлений ВМЕСТЕ С КОММЕНТАРИЕМ.
 * Живёт здесь, рядом с разборщиком: сторож палитры сверял число подстрокой
 * (`toContain("5,58")`), то есть проверял, что рядом с токеном стоит нужный
 * текст. Согласованно изменённая НЕВЕРНАЯ пара «значение + число» проходила
 * зелёной, и это не гипотеза: в срезе Д1 нашлось число «2,88:1», не совпадавшее
 * ни с одной из трёх поверхностей, — нашёл его человек пересчётом.
 *
 * `правилаCss` комментарии ВЫРЕЗАЕТ (иначе сканер спотыкался бы о скобки в
 * прозе), поэтому объявления с комментариями разбираются отдельно и построчно.
 */

/** Объявление токена вместе с комментарием, стоящим на ТОЙ ЖЕ строке. */
export type ОбъявлениеСКомментарием = {
  токен: string;
  значение: string;
  комментарий: string;
  /** Номер строки в файле — чтобы упавший сторож называл место, а не токен. */
  строка: number;
};

/**
 * Объявления кастомных свойств, у которых на строке есть комментарий.
 *
 * Построчно, а не по телу правила: комментарий привязан именно к строке
 * («число относится к ЭТОМУ значению»), и в теле правила эта привязка теряется.
 */
export function объявленияСКомментарием(source: string): ОбъявлениеСКомментарием[] {
  const итог: ОбъявлениеСКомментарием[] = [];
  const строки = source.split("\n");
  for (let i = 0; i < строки.length; i += 1) {
    const m = /^\s*(--[a-z0-9-]+)\s*:\s*([^;{}]+);\s*\/\*(.*?)\*\//i.exec(строки[i] ?? "");
    if (m === null) continue;
    итог.push({
      токен: m[1] ?? "",
      значение: (m[2] ?? "").trim(),
      комментарий: (m[3] ?? "").trim(),
      строка: i + 1,
    });
  }
  return итог;
}

/** Цвет `#rgb`/`#rrggbb` в каналы 0…255; иначе `null` — считать нечего. */
function каналы(цвет: string): [number, number, number] | null {
  const m = /^#([0-9a-f]{3}|[0-9a-f]{6})$/.exec(цвет.trim().toLowerCase());
  if (m === null) return null;
  const цифры = m[1] ?? "";
  const канал = (номер: number): number =>
    цифры.length === 3
      ? Number.parseInt((цифры[номер] ?? "0").repeat(2), 16)
      : Number.parseInt(цифры.slice(номер * 2, номер * 2 + 2), 16);
  return [канал(0), канал(1), канал(2)];
}

/**
 * Относительная яркость по WCAG 2 (§ relative luminance): канал линеаризуется
 * (порог 0,04045, гамма 2,4), дальше веса 0,2126 / 0,7152 / 0,0722.
 *
 * Формула переписана здесь ЦЕЛИКОМ и намеренно: сторож обязан считать сам, а не
 * спрашивать библиотеку, иначе «проверено» снова означало бы «совпало с тем же
 * источником, из которого число и взяли».
 */
function яркость(цвет: string): number | null {
  const rgb = каналы(цвет);
  if (rgb === null) return null;
  const линейный = (канал: number): number => {
    const s = канал / 255;
    return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * линейный(rgb[0]) + 0.7152 * линейный(rgb[1]) + 0.0722 * линейный(rgb[2]);
}

/**
 * Контраст двух цветов по WCAG: `(светлее + 0,05) / (темнее + 0,05)`.
 * `null` — хотя бы один цвет не разобрался (не hex): считать нечего.
 */
export function контраст(a: string, b: string): number | null {
  const x = яркость(a);
  const y = яркость(b);
  if (x === null || y === null) return null;
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
}
