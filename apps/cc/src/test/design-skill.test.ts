/** Проверки идут по тексту без переносов: правило можно перенести иначе. */
const склеить = (s: string): string => s.replace(/\s+/g, " ");

/** Строка markdown-таблицы по метке — чтобы факт искался в своей строке, а не во всём файле. */
const строкаТаблицы = (текст: string, метка: string): string =>
  текст.split("\n").find((строка) => строка.includes(метка)) ?? "";

