/**
 * Тело ПОСЛЕДНЕГО CSS-правила с этим селектором — тем же разборщиком, что у
 * сторожа палитры и сторожа колоночности (`test/css.ts`). Поиском подстроки
 * нельзя: многострочное правило нашлось бы по одной строке селектора, а
 * комментарий рядом с ним прочитался бы как объявление.
 *
 * ПОСЛЕДНЕГО, А НЕ ПЕРВОГО (девятый круг починок, 3.3): браузер при равной
 * специфичности применяет то правило, что ниже по файлу, — сторож обязан
 * судить о том же.
 */
function телоПравила(селектор: string): string {
  const правило = последнееПравило(стилиПанели, селектор);
  expect(правило, `в globals.css нет правила ${селектор}`).not.toBeNull();
  return правило?.тело ?? "";
}

/**
 * Шапка §4 — от заголовка до первого подраздела: сюда срез Д2 положил механизм
 * темы, здесь же стоит копия списка маршрутов.
 *
 * ОБЕ ГРАНИЦЫ ПРОВЕРЯЮТСЯ ЯВНО, как в `theme-routes.test.ts`. Нижняя не была
 * пришпилена, и снятие ОДНОЙ точки у подзаголовка («### 4.1.» → «### 4.1»)
 * оставляло весь набор зелёным, расширяя вырезку с ~4,8 тыс. знаков до ~20 тыс.,
 * то есть почти до всего файла: сторожа ниже продолжали бы утверждать «§4
 * описывает механизм темы», даже если механизм переехал в §8. Сторож молча
 * превращается из «§4 называет факт» в «файл где-нибудь упоминает слово».
 * У соседей (§4.3, §9) та же поломка вырождает вырезку в пустую строку и
 * сестринский ассерт краснеет сам; у §4 — нет, поэтому границы здесь ручные.
 */
function шапка4(): string {
  const от = правилаОдной.indexOf("## 4. ");
  const до = правилаОдной.indexOf("### 4.1.");
  expect(от, "в rules.md нет заголовка «## 4. »").toBeGreaterThan(-1);
  expect(до, "в rules.md нет подзаголовка «### 4.1.» после §4").toBeGreaterThan(от);
  return правилаОдной.slice(от, до);
}

