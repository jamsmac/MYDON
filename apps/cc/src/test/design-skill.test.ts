/*
 * Навык не должен ВРАТЬ ПРО КОД: утверждения, которые он теперь печатает,
 * сверяются с настоящим globals.css. Иначе документ разойдётся с CSS ровно так,
 * как разошёлся маршрутный список темы, — и снова молча.
 */
describe("навык не врёт про код", () => {
  it("--unk объявлен во всех трёх блоках палитры", () => {
    const блоки = правилаCss(стилиПанели).filter((r) => /--unk\s*:/.test(r.тело));
    expect(
      блоки.length,
      "нужны :root, @media (prefers-color-scheme: dark) и :root[data-theme=dark]",
    ).toBeGreaterThanOrEqual(3);
  });

  it("лампа «нет данных» берёт --unk, а не третичный текст", () => {
    expect(телоПравила(".led.unknown")).toContain("var(--unk)");
  });

  it("полоса внимания берёт --warn, а лампа «работает» остаётся оранжевой", () => {
    expect(телоПравила('.agtile[data-attention="true"]')).toContain("var(--warn)");
    expect(телоПравила(".led.working")).toContain("var(--accent-tx)");
  });

  it("перенос строки источника под 520px в CSS есть — §4.2 не врёт (Ф-3)", () => {
    const ступени = правилаCss(стилиПанели)
      .filter((r) => r.селектор === ".approw" && /flex-wrap/.test(r.тело))
      .map((r) => r.контекст);
    expect(ступени, "правило переноса `.approw` пропало из globals.css").toContain(
      "@media (max-width: 520px)",
    );
  });

  it("числа контраста в tokens.md сходятся с РАСЧЁТОМ по значениям globals.css (Ф-2)", () => {
    /*
     * ЗДЕСЬ ЗАКРЫВАЕТСЯ ТЁМНАЯ ВЕТКА. Сторож палитры считает контраст только по
     * комментариям НА СТРОКЕ объявления, а в тёмных блоках их нет ни одного:
     * `--warn: #e8b866` можно было поменять на что угодно, и четыре
     * напечатанных числа (9,03/9,94 в блоке `.agtile[data-attention]`
     * `globals.css`, те же в `tokens.md` и `rules.md` §4.2) стали бы неверными
     * при зелёных тестах.
     *
     * ЧИСЛА БЕРУТСЯ ИЗ `tokens.md`, А НЕ ИЗ ТРЕТЬЕЙ КОПИИ В ТЕСТЕ: сторож
     * обязан сверять УТВЕРЖДЕНИЕ навыка с расчётом, а не текст с текстом.
     * Порядок пары задан шапкой самого навыка — «на карточке `--surf` / на
     * холсте `--bg`», и он уже проверен тестом выше.
     */
    const формат = (значение: number): string => значение.toFixed(2).replace(".", ",");
    const контрастВ = (ветка: Ветка, токен: string, поверхность: string): string => {
      const карта = палитраБлока(стилиПанели, ветка);
      const цвет = карта.get(токен);
      const фон = карта.get(поверхность);
      expect(цвет, `в блоке «${ветка.имя}» нет ${токен}`).toBeDefined();
      expect(фон, `в блоке «${ветка.имя}» нет ${поверхность}`).toBeDefined();
      const значение = контраст(цвет ?? "", фон ?? "");
      expect(значение, `${токен} на ${поверхность}: цвет не разобрался`).not.toBeNull();
      return формат(значение ?? 0);
    };

    for (const токен of ["--warn", "--unk"]) {
      const строка = строкаТаблицы(токены, `\`${токен}\``);
      const числа = /светлая\s+(\d+,\d+)\s*\/\s*(\d+,\d+),\s*тёмная\s+(\d+,\d+)\s*\/\s*(\d+,\d+)/.exec(
        строка,
      );
      expect(числа, `в строке ${токен} нет пары «светлая A / B, тёмная C / D»`).not.toBeNull();
      const [, свКарточка, свХолст, тёмКарточка, тёмХолст] = числа ?? [];
      expect([свКарточка, свХолст], `${токен}: светлые числа не сходятся с расчётом`).toEqual([
        контрастВ(СВЕТЛАЯ, токен, "--surf"),
        контрастВ(СВЕТЛАЯ, токен, "--bg"),
      ]);
      // Тёмная ветка одна: вторую (`[data-theme="dark"]`) сторож палитры
      // сверяет с этой пословно, значениями и именами.
      expect([тёмКарточка, тёмХолст], `${токен}: тёмные числа не сходятся с расчётом`).toEqual([
        контрастВ(ТЁМНАЯ_СИСТЕМНАЯ, токен, "--surf"),
        контрастВ(ТЁМНАЯ_СИСТЕМНАЯ, токен, "--bg"),
      ]);
    }

    // ТРЕТЬЯ КОПИЯ ЧИСЕЛ — блочный комментарий у правила полосы внимания.
    // Проверяется присутствием посчитанного: разбирать прозу целиком дороже,
    // чем она стоит, а разъехаться она может только вместе со значением.
    for (const поверхность of ["--surf", "--bg"]) {
      const число = контрастВ(ТЁМНАЯ_СИСТЕМНАЯ, "--warn", поверхность);
      expect(стилиПанели, `в globals.css нет посчитанного ${число}:1 для тёмного --warn`).toContain(
        `${число}:1`,
      );
    }
  });

  it("ступени колонок в CSS — ровно те, что печатает §4.3", () => {
    const ступени = правилаCss(стилиПанели)
      .filter((r) => r.селектор === ".aggrid" && r.тело.includes("grid-template-columns"))
      .map((r) => r.контекст);
    expect(ступени).toContain("");
    expect(ступени).toContain("@media (min-width: 720px)");
    expect(ступени).toContain("@media (min-width: 1200px)");
  });

  it("color-scheme объявлен во всех трёх блоках темы — §4 и §8 не врут", () => {
    const схема = (ветка: Ветка, ожидаемая: string): void => {
      const блоки = правилаCss(стилиПанели).filter(
        (r) =>
          r.контекст === ветка.контекст && r.селектор === ветка.селектор && /color-scheme\s*:/.test(r.тело),
      );
      expect(блоки.length, `в блоке «${ветка.имя}» нет color-scheme`).toBeGreaterThanOrEqual(1);
      expect(блоки.at(-1)?.тело ?? "", `в блоке «${ветка.имя}» color-scheme не ${ожидаемая}`).toMatch(
        new RegExp(`color-scheme\\s*:\\s*${ожидаемая}\\b`),
      );
    };
    схема(СВЕТЛАЯ, "light");
    схема(ТЁМНАЯ_СИСТЕМНАЯ, "dark");
    схема(ТЁМНАЯ_ВЫБРАННАЯ, "dark");
  });

  it("точечная сетка стоит на холсте командного центра, только в тёмной теме и не в панели", () => {
    const сетки = правилаCss(стилиПанели).filter((r) => /radial-gradient/.test(r.тело));
    const наХолсте = сетки.filter((r) => r.селектор.includes('.app[data-console="true"]'));
    expect(наХолсте.length, 'в globals.css нет правила сетки на .app[data-console="true"]').toBeGreaterThanOrEqual(1);
    for (const правило of наХолсте) {
      expect(правило.тело, "шаг сетки — 24px, как печатает §4").toContain("24px");
      expect(
        `${правило.контекст} ${правило.селектор}`,
        "сетка обязана быть заперта в тёмной теме — §4 обещает светлому миру холст без неё",
      ).toMatch(/data-theme="dark"\]|prefers-color-scheme: dark/);
    }
    for (const r of сетки) {
      expect(r.селектор, `сетка вложена в панель или карточку: ${r.селектор}`).not.toMatch(/\.panel|\.card/);
    }
  });

  it("ручного штампа темы нет, а названные в §4 файлы механизма существуют", () => {
    expect(
      existsSync(path.join(КОРЕНЬ, "apps/cc/src/components/console-theme.tsx")),
      "console-theme.tsx вернулся — §4 снова врёт про штамп на странице",
    ).toBe(false);
    for (const файл of [
      "apps/cc/src/lib/theme.ts",
      "apps/cc/src/proxy.ts",
      "apps/cc/src/components/theme-sync.tsx",
      "apps/cc/src/app/theme/actions.ts",
      "apps/cc/src/components/header-actions.tsx",
    ]) {
      expect(existsSync(path.join(КОРЕНЬ, файл)), `§4 ссылается на ${файл}, а его нет`).toBe(true);
    }
  });

  it("доски из primitives.md существуют в CSS теми же селекторами", () => {
    for (const селектор of [
      ".crons-table",
      ".crons-table tr.is-paused td",
      ".flight",
      ".ph",
      '.ph[data-state="skip"]',
      ".flows-layout",
      ".flows-layout.reading .flow-detail",
      ".flow-timeline",
      "article.doc",
      ".approw",
      '.approw[data-state="unknown"]',
      ".aghead",
      ".docs-layout",
      ".docs-layout.reading .docs-body",
      ".brain-card-head",
    ]) {
      телоПравила(селектор);
    }
    // Одно число гашения на все доски — навык это утверждает, CSS обязан держать.
    expect(телоПравила(".crons-table tr.is-paused td")).toContain("0.55");
    expect(телоПравила('.ph[data-state="skip"]')).toContain("0.55");
    expect(телоПравила('.approw[data-state="unknown"]')).toContain("dashed");
  });
});

