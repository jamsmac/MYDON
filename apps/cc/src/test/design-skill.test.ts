/*
 * Навык не должен ВРАТЬ ПРО КОД: утверждения, которые он теперь печатает,
 * сверяются с настоящим globals.css. Иначе документ разойдётся с CSS ровно так,
 * как разошёлся маршрутный список темы, — и снова молча.
 */
describe("навык не врёт про код", () => {
  it("--unk объявлен во всех трёх блоках палитры", () => {
    const блоки = правилаCss(стилиПанели).filter((r) => /--unk\s*:/.test(r.тело));
    expect(
      блоки.length,
      "нужны :root, @media (prefers-color-scheme: dark) и :root[data-theme=dark]",
    ).toBeGreaterThanOrEqual(3);
  });

  it("лампа «нет данных» берёт --unk, а не третичный текст", () => {
    expect(телоПравила(".led.unknown")).toContain("var(--unk)");
  });

  it("полоса внимания берёт --warn, а лампа «работает» остаётся оранжевой", () => {
    expect(телоПравила('.agtile[data-attention="true"]')).toContain("var(--warn)");
    expect(телоПравила(".led.working")).toContain("var(--accent-tx)");
  });

  it("ступени колонок в CSS — ровно те, что печатает §4.3", () => {
    const ступени = правилаCss(стилиПанели)
      .filter((r) => r.селектор === ".aggrid" && r.тело.includes("grid-template-columns"))
      .map((r) => r.контекст);
    expect(ступени).toContain("");
    expect(ступени).toContain("@media (min-width: 720px)");
    expect(ступени).toContain("@media (min-width: 1200px)");
  });
});

/*
 * Зеркала. `.agents/skills` адресовано Codex и отличается ОСОЗНАННО ровно двумя
 * заменами (свой файл конвенций, своё имя автора макетов) — всё прочее
 * расхождение дрейф. Стартер (`docs/agentic-os-starter/claude-skills`) —
 * дословная копия: его ставит `apply.sh` в чужой репозиторий как `.claude/skills`.
 */
const ЗЕРКАЛЬНЫЕ_ФАЙЛЫ = ["rules.md", "tokens.md", "primitives.md", "checklist.md"] as const;
const ЗАМЕНЫ_ДЛЯ_CODEX: readonly (readonly [string, string])[] = [
  ["CLAUDE.md", "AGENTS.md"],
  ["макеты Claude Design", "макеты Codex Design"],
];

describe("зеркала навыка mydon-design не разъезжаются", () => {
  for (const зеркало of [ЗЕРКАЛО_CODEX, ЗЕРКАЛО_СТАРТЕРА]) {
    const имя = path.relative(КОРЕНЬ, зеркало);
    for (const файл of ЗЕРКАЛЬНЫЕ_ФАЙЛЫ) {
      it(`${имя}/${файл} совпадает с .claude/skills дословно`, () => {
        expect(читать(зеркало, файл)).toBe(читать(НАВЫК, файл));
      });
    }
  }

  it("SKILL.md зеркала для Codex отличается только объявленными заменами", () => {
    let ожидаемый = читать(НАВЫК, "SKILL.md");
    for (const [из, во] of ЗАМЕНЫ_ДЛЯ_CODEX) ожидаемый = ожидаемый.split(из).join(во);
    expect(читать(ЗЕРКАЛО_CODEX, "SKILL.md")).toBe(ожидаемый);
  });

  it("SKILL.md стартера — дословная копия", () => {
    expect(читать(ЗЕРКАЛО_СТАРТЕРА, "SKILL.md")).toBe(читать(НАВЫК, "SKILL.md"));
  });

  it("сплошная замена «Claude»→«Codex» не воскресла: ссылка на бриф цела", () => {
    // Прежний сплошной replace превращал существующий
    // `docs/PROMPT-CLAUDE-DESIGN.md` в несуществующий `PROMPT-Codex-DESIGN.md`
    // — битая ссылка в карте хуже отсутствия карты.
    expect(читать(ЗЕРКАЛО_CODEX, "SKILL.md")).toContain("docs/PROMPT-CLAUDE-DESIGN.md");
  });
});
