/**
 * Тело ПОСЛЕДНЕГО CSS-правила с этим селектором — тем же разборщиком, что у
 * сторожа палитры и сторожа колоночности (`test/css.ts`). Поиском подстроки
 * нельзя: многострочное правило нашлось бы по одной строке селектора, а
 * комментарий рядом с ним прочитался бы как объявление.
 *
 * ПОСЛЕДНЕГО, А НЕ ПЕРВОГО (девятый круг починок, 3.3): браузер при равной
 * специфичности применяет то правило, что ниже по файлу, — сторож обязан
 * судить о том же.
 */
function телоПравила(селектор: string): string {
  const правило = последнееПравило(стилиПанели, селектор);
  expect(правило, `в globals.css нет правила ${селектор}`).not.toBeNull();
  return правило?.тело ?? "";
}

