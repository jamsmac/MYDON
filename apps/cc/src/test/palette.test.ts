/*
 * Сторож палитры состояний. Правила живут в CSS, а jsdom стилей не применяет —
 * поэтому сторожим САМ ФАЙЛ, как сторож затемнения паузы из волны A2
 * (`components/agent-grid.test.tsx`).
 *
 * РАЗБОРОМ, А НЕ ПОИСКОМ ПОДСТРОК. Тёмная тема объявлена в файле ДВАЖДЫ и
 * синхронизируется руками: токен, добавленный только в одну ветку, поиском
 * подстроки `--unk` выглядит объявленным везде, а на половине пользователей
 * не работает. И сравнение имён токенов недостаточно: в светлой теме `--hot`
 * и `--accent-tx` — один и тот же #b8480f, так что «разные имена» ещё не
 * значит «разные тона».
 *
 * Сканер и чтение файла переехали в `test/css.ts` (срез Д1, задача 5): тот же
 * разбор понадобился сторожу колоночности сетки агентов, а второй экземпляр
 * скобочного сканера разошёлся бы с этим ровно так же, как разъезжались
 * словари состояний.
 */

/**
 * Палитра одной ветки: имя токена → значение.
 *
 * Разбор переехал в `test/css.ts` (круг починок Ф-2): к палитре по веткам ходит
 * ещё и сторож навыка, сверяющий напечатанные числа контраста с расчётом.
 * Ассерт «блок нашёлся» остаётся здесь — это утверждение сторожа палитры, а не
 * работа разборщика: пустая карта у него значила бы «токенов нет», и все
 * проверки ниже прошли бы зелёными на пустом месте.
 */
function палитра(ветка: Ветка): Map<string, string> {
  const карта = палитраБлока(css, ветка);
  expect(карта.size, `блок палитры «${ветка.имя}» в globals.css не найден`).toBeGreaterThan(0);
  return карта;
}

/**
 * Имя токена, которым правило задаёт свойство. Сравнивать имя честнее, чем
 * текст правила: `border-left: 3px solid var(--warn)` и
 * `border-left: 3px var(--warn) solid` — одно и то же.
 *
 * БЕРЁТСЯ ПОСЛЕДНЕЕ ОБЪЯВЛЕНИЕ, И ПРАВИЛО ТОЖЕ ПОСЛЕДНЕЕ (девятый круг
 * починок, 3.3). Внутри правила «последнее» тут было с самого начала, а вот
 * ПРАВИЛА перебирались до первого попадания — то есть сторож судил о первом
 * правиле файла, а браузер применяет последнее. Дубль ниже по файлу
 * переопределял проверенное значение молча.
 */
function токенСвойства(селектор: string, свойство: string): string | null {
  const правило = последнееПравило(css, селектор);
  if (правило === null) return null;
  const все = [...правило.тело.matchAll(new RegExp(`(?:^|[;\\s])${свойство}\\s*:\\s*([^;{}]+)`, "gi"))];
  const значение = все.at(-1)?.[1] ?? "";
  const токен = значение.match(/var\(\s*(--[a-z0-9-]+)/i);
  return токен ? (токен[1] ?? null) : null;
}

/** Числа контраста («5,58») из комментария на строке объявления токена. */
function контрастВКомментарии(имя: string): string[] {
  return объявленияСКомментарием(css)
    .filter((о) => о.токен === имя)
    .flatMap((о) => числаКонтраста(о.комментарий).map((ч) => ч.число));
}

/**
 * Числа в записи отношения («5,58:1») вместе с текстом, стоящим ПЕРЕД ними.
 *
 * ЗАПИСЬ «:1» — ЭТО КРЮЧОК, а не украшение: в значениях и комментариях палитры
 * хватает других дробей («rgba(…, 0,12)», «раз в 5 минут»), и без крючка сторож
 * пошёл бы считать контраст прозрачности. Текст перед числом нужен потому, что
 * поверхность называется словом ровно там: «белый на нём 5,72:1».
 */
function числаКонтраста(комментарий: string): { число: string; перед: string }[] {
  const итог: { число: string; перед: string }[] = [];
  let хвост = 0;
  for (const m of комментарий.matchAll(/(\d+,\d+):1/g)) {
    const начало = m.index ?? 0;
    итог.push({ число: m[1] ?? "", перед: комментарий.slice(хвост, начало) });
    хвост = начало + m[0].length;
  }
  return итог;
}

/**
 * Поверхности, к которым может относиться число, и слова, которыми комментарий
 * их называет.
 *
 * ПОРЯДОК ОПРЕДЕЛЯЕТ БЛИЖАЙШЕЕ СЛОВО, А НЕ СПИСОК: берётся то название,
 * которое стоит ПОСЛЕДНИМ перед числом, — иначе у `--err` («5,18:1, белый на
 * нём 5,72:1») оба числа достались бы одной поверхности. Ничего не названо —
 * действует правило шапки globals.css: «число в комментарии — отношение к
 * холсту `--bg`, если не сказано иное».
 */
const ПОВЕРХНОСТИ: readonly { слова: RegExp; имя: string; цвет: string }[] = [
  { слова: /чернил/i, имя: "тёмные чернила (--tx)", цвет: "--tx" },
  { слова: /бел(ый|ым|ого|ом)/i, имя: "белый (#ffffff)", цвет: "#ffffff" },
  { слова: /карточк/i, имя: "карточка (--surf)", цвет: "--surf" },
  { слова: /surf-2|приподнят/i, имя: "приподнятое (--surf-2)", цвет: "--surf-2" },
  { слова: /холст/i, имя: "холст (--bg)", цвет: "--bg" },
];
const ХОЛСТ = { имя: "холст (--bg, по правилу шапки файла)", цвет: "--bg" };

/** Поверхность, названная последней перед числом; не названа — холст. */
function поверхностьЧисла(перед: string): { имя: string; цвет: string } {
  let выбор = ХОЛСТ;
  let место = -1;
  for (const п of ПОВЕРХНОСТИ) {
    const все = [...перед.matchAll(new RegExp(п.слова.source, "gi"))];
    const последнее = все.at(-1)?.index ?? -1;
    if (последнее > место) {
      место = последнее;
      выбор = { имя: п.имя, цвет: п.цвет };
    }
  }
  return выбор;
}

/** Цвет поверхности в этой ветке темы: литерал как есть, токен — из палитры. */
function цветПоверхности(ветка: Ветка, цвет: string): string | undefined {
  return цвет.startsWith("#") ? цвет : палитра(ветка).get(цвет);
}

/** Число в записи файла: запятая как разделитель, знаков — сколько обещано. */
function какВФайле(значение: number, знаков: number): string {
  return значение.toFixed(знаков).replace(".", ",");
}

