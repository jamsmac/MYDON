import { describe, expect, it } from "vitest";
import { правилаCss as правила, стилиПанели as css } from "./css";

/*
 * Сторож палитры состояний. Правила живут в CSS, а jsdom стилей не применяет —
 * поэтому сторожим САМ ФАЙЛ, как сторож затемнения паузы из волны A2
 * (`components/agent-grid.test.tsx`).
 *
 * РАЗБОРОМ, А НЕ ПОИСКОМ ПОДСТРОК. Тёмная тема объявлена в файле ДВАЖДЫ и
 * синхронизируется руками: токен, добавленный только в одну ветку, поиском
 * подстроки `--unk` выглядит объявленным везде, а на половине пользователей
 * не работает. И сравнение имён токенов недостаточно: в светлой теме `--hot`
 * и `--accent-tx` — один и тот же #b8480f, так что «разные имена» ещё не
 * значит «разные тона».
 *
 * Сканер и чтение файла переехали в `test/css.ts` (срез Д1, задача 5): тот же
 * разбор понадобился сторожу колоночности сетки агентов, а второй экземпляр
 * скобочного сканера разошёлся бы с этим ровно так же, как разъезжались
 * словари состояний.
 */

/** Объявления кастомных свойств в теле правила: имя → значение. */
function токены(тело: string): Map<string, string> {
  const карта = new Map<string, string>();
  for (const m of тело.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;{}]+)/gi)) {
    карта.set(m[1] ?? "", (m[2] ?? "").trim());
  }
  return карта;
}

type Ветка = { имя: string; контекст: string; селектор: string };

/* Три блока палитры: светлая база и ДВЕ ветки тёмной темы. Отдельными
   константами, а не индексами массива: `ВЕТКИ[1]` в тесте ничего не называет. */
const СВЕТЛАЯ: Ветка = { имя: "светлая (:root)", контекст: "", селектор: ":root" };
const ТЁМНАЯ_СИСТЕМНАЯ: Ветка = {
  имя: "тёмная системная (@media prefers-color-scheme: dark)",
  контекст: "@media (prefers-color-scheme: dark)",
  селектор: ':root:not([data-theme="light"])',
};
const ТЁМНАЯ_ВЫБРАННАЯ: Ветка = {
  имя: 'тёмная выбранная (:root[data-theme="dark"])',
  контекст: "",
  селектор: ':root[data-theme="dark"]',
};
const ВЕТКИ: readonly Ветка[] = [СВЕТЛАЯ, ТЁМНАЯ_СИСТЕМНАЯ, ТЁМНАЯ_ВЫБРАННАЯ];

/** Палитра одной ветки: имя токена → значение. */
function палитра(ветка: Ветка): Map<string, string> {
  const найдено = правила(css).filter(
    (r) => r.контекст === ветка.контекст && r.селектор === ветка.селектор,
  );
  expect(найдено.length, `блок палитры «${ветка.имя}» в globals.css не найден`).toBeGreaterThan(0);
  const карта = new Map<string, string>();
  for (const r of найдено) for (const [имя, значение] of токены(r.тело)) карта.set(имя, значение);
  return карта;
}

/**
 * Имя токена, которым правило задаёт свойство. Сравнивать имя честнее, чем
 * текст правила: `border-left: 3px solid var(--warn)` и
 * `border-left: 3px var(--warn) solid` — одно и то же.
 */
function токенСвойства(селектор: string, свойство: string): string | null {
  for (const r of правила(css)) {
    if (!r.селектор.split(",").some((s) => s.trim() === селектор)) continue;
    const все = [...r.тело.matchAll(new RegExp(`(?:^|[;\\s])${свойство}\\s*:\\s*([^;{}]+)`, "gi"))];
    const значение = все.at(-1)?.[1] ?? "";
    const токен = значение.match(/var\(\s*(--[a-z0-9-]+)/i);
    if (токен) return токен[1] ?? null;
  }
  return null;
}

/** Числа контраста («5,58») из комментария на строке объявления токена. */
function контрастВКомментарии(имя: string): string[] {
  return css
    .split("\n")
    .filter((строка) => new RegExp(`^\\s*${имя}\\s*:`).test(строка))
    .flatMap((строка) => [...строка.matchAll(/\d+,\d+/g)].map((m) => m[0] ?? ""));
}

describe("Палитра globals.css: токен «нет данных»", () => {
  it("--unk объявлен во всех ТРЁХ блоках темы", () => {
    for (const ветка of ВЕТКИ) {
      expect(палитра(ветка).get("--unk"), `в блоке «${ветка.имя}» нет --unk`).toBeDefined();
    }
  });

  it("значения --unk — ровно те, для которых посчитан контраст", () => {
    expect(палитра(СВЕТЛАЯ).get("--unk")).toBe("#5c6360");
    expect(палитра(ТЁМНАЯ_СИСТЕМНАЯ).get("--unk")).toBe("#9aa39b");
    expect(палитра(ТЁМНАЯ_ВЫБРАННАЯ).get("--unk")).toBe("#9aa39b");
  });

  it("«не оценить» красится своим токеном, а не третичным текстом", () => {
    expect(токенСвойства(".led.unknown", "color")).toBe("--unk");
  });

  it("две ветки тёмной темы объявляют ОДИН набор токенов", () => {
    // Списки продублированы вручную (комментарий «Объявлена ДВАЖДЫ намеренно»):
    // новый токен в одной ветке и забытый в другой — регресс, который видно
    // только на половине пользователей.
    expect([...палитра(ТЁМНАЯ_ВЫБРАННАЯ).keys()].sort()).toEqual(
      [...палитра(ТЁМНАЯ_СИСТЕМНАЯ).keys()].sort(),
    );
  });
});

describe("Палитра globals.css: полоса внимания и лампа «работает»", () => {
  const полоса = токенСвойства('.agtile[data-attention="true"]', "border-left");
  const лампаРаботает = токенСвойства(".led.working", "color");

  it("полоса внимания носит --warn, лампа «работает» — --accent-tx", () => {
    expect(полоса).toBe("--warn");
    expect(лампаРаботает).toBe("--accent-tx");
  });

  it("лампа сломанного молчуна ушла с оранжевого вместе с полосой", () => {
    // `agent-grid.tsx` ставит сломанному молчуну класс `led run-led warn`
    // ВМЕСТО словаря состояний: останься `.run-led.warn` на `--accent-tx`,
    // плитка снова была бы одного тона с «работает».
    expect(токенСвойства(".run-led.warn", "color")).toBe("--warn");
  });

  it("это разные ТОНА в каждой ветке темы, а не только разные имена", () => {
    for (const ветка of ВЕТКИ) {
      const карта = палитра(ветка);
      const тонПолосы = карта.get(полоса ?? "");
      const тонЛампы = карта.get(лампаРаботает ?? "");
      expect(тонПолосы, `в блоке «${ветка.имя}» не объявлен ${полоса}`).toBeDefined();
      expect(тонЛампы, `в блоке «${ветка.имя}» не объявлен ${лампаРаботает}`).toBeDefined();
      expect(
        тонПолосы,
        `в блоке «${ветка.имя}» полоса внимания и лампа «работает» одного тона`,
      ).not.toBe(тонЛампы);
    }
  });

  it("рамка фазы «предупреждение» одного тона со своей лампой", () => {
    // В клетке полосы фаз лампа рисуется классом `run-led warn`
    // (`flow-strip.tsx`), а рамка — атрибутом `data-state`. Разъедутся токены —
    // одна клетка станет двумя разными сигналами.
    expect(токенСвойства('.ph[data-state="warn"]', "border-color")).toBe("--warn");
    expect(токенСвойства('.ph[data-state="warn"]', "border-color")).toBe(
      токенСвойства(".run-led.warn", "color"),
    );
  });

  it("полоса затыка осталась на --err и стоит в файле ДО полосы внимания", () => {
    // Оба правила ставят `border-left` на ОДНОМ элементе. Состояниями они не
    // пересекаются (`blocked` ≠ `idle`), но если пересекутся — победит
    // последнее в файле, и это должно быть внимание.
    expect(токенСвойства('.agtile[data-state="blocked"]', "border-left")).toBe("--err");
    const без = css.replace(/\/\*[\s\S]*?\*\//g, "");
    const затык = без.indexOf('.agtile[data-state="blocked"]');
    const внимание = без.indexOf('.agtile[data-attention="true"]');
    expect(затык).toBeGreaterThan(-1);
    expect(внимание).toBeGreaterThan(затык);
  });
});

describe("Палитра globals.css: контраст записан рядом со значением", () => {
  it("у --unk посчитан контраст к холсту", () => {
    expect(контрастВКомментарии("--unk")).toContain("5,58");
  });

  it("у --warn посчитан контраст — он был единственным токеном палитры без числа", () => {
    expect(контрастВКомментарии("--warn")).toContain("5,37");
  });
});
