/**
 * СОСТЯЗАТЕЛЬНЫЙ ПЕРЕБОР ИНВАРИАНТА (срез Д1, П4).
 *
 * Инвариант среза: `state === "ok"` ⇒ `lastCheckedAt !== null`. Зелёная строка
 * ОБЯЗАНА нести время проверки — иначе панель говорит «в порядке» о том, чего
 * никто не проверял, и это ровно та ложь, ради которой волна A2 завела третье
 * состояние.
 *
 * ПОЧЕМУ ПЕРЕБОР, А НЕ ЕЩЁ ДЕСЯТЬ ПРИМЕРОВ. Инвариант держится не на одной
 * ветке, а на СОГЛАСОВАННОСТИ полутора десятков: каждая зелёная ветка берёт
 * момент проверки из своего поля, и любая новая ветка (или новый источник
 * моментов) может его потерять. Пример ловит то, о чём автор подумал; перебор
 * ловит то, о чём он не подумал. Такой перебор доказал инвариант при ревью
 * задачи 2 — на 90 283 входах, 9 242 зелёных строках, — но был одноразовой
 * оснасткой и умер вместе с сессией ревьюера. Здесь он живёт в репозитории.
 *
 * ЧТО ИМЕННО ПЕРЕБИРАЕТСЯ. Произведение ФОРМ, а не случайные значения: шесть
 * форм `Date` (нет, `undefined`, `Invalid Date`, свежая, старая, будущая) и
 * семь форм ISO (нет, пустая, мусор, с зоной свежая, с зоной старая, форма СУБД
 * «YYYY-MM-DD HH:mm:ss», голая дата) — по ВСЕМ точкам правил, включая
 * `unavailableRow`. Число входов вторично: важна полнота произведения, потому
 * что ломается именно стык форм («момент есть, но не читается» × «ветка судит
 * по другому полю»).
 *
 * ШЕСТЬ УТВЕРЖДЕНИЙ И ОДНО СЧЁТНОЕ:
 *   1) нет `ok` без `lastCheckedAt`;
 *   2) правила не бросают (`toISOString()` на `Invalid Date` — это `RangeError`
 *      ПРЯМО ИЗ ЧИСТЫХ ПРАВИЛ, то есть 500 на весь `/apps/health`);
 *   3) наружу не едет ни битый ISO, ни подстрока `NaN`;
 *   4) невозможной пары «момент известен, а о проверках не знаем» не бывает
 *      (`checksKnown === false` ⇒ `lastCheckedAt === null`, круг починок Ф-1):
 *      момент — это и есть знание, и разъехаться этой паре нечем только пока
 *      её собирают два места;
 *   5) УТВЕРЖДЕНИЕ «проверок не было» (`checksKnown === true` при пустом
 *      `lastCheckedAt`) стоит ТОЛЬКО там, где во входе нет ни одного
 *      свидетельства проверок И ВХОД ПРОЧИТАН (девятый круг починок, К-1).
 *      Обратного утверждения к пункту 4 не существовало, и перебор был ЗЕЛЁНЫМ
 *      НА ДЕФЕКТЕ: он кормил правила входами «двадцать прогонов в отчёте,
 *      момента нет» и «зависших резервов 4», а строка отвечала «не запускался».
 *      Что считать свидетельством, знает не перебор вообще, а каждый раздел про
 *      свой источник — предикат передаётся рядом с входом;
 *   6) ОБРАТНАЯ ПОЛЯРНОСТЬ К ПУНКТУ 5 (десятый круг починок, Ф-2): «не знаем»
 *      при пустом `lastCheckedAt` стоит ТОЛЬКО там, где во входе есть
 *      свидетельство ЛИБО вход не прочитан. Ноль свидетельств по прочитанному
 *      входу обязан стать утверждением, а не скромностью. Без этого пункта
 *      перебор был закрыт В ОДНУ СТОРОНУ: мутации «лишний признак
 *      свидетельства у ledger» (`+ budgetRemainingUsd > 0`) и «`pending` в
 *      счёт закрытых у очереди» проходили 7/7 зелёными — построчно их не
 *      ловил никто, а счётчик `неЗапускался` с запасом втрое (5 → 2 при пороге
 *      1, 648 → 486 при пороге 210) их не замечал. Поэтому предикат входа
 *      ТРЁХЗНАЧНЫЙ: «свидетельства есть» / «нет, вход прочитан» / «вход не
 *      прочитан» — двузначный не умеет отличить непрочитанное от пустого, а
 *      ровно на этом различии стоят оба пункта;
 *   7) СЧЁТНОЕ: строк каждого рода ЗАМЕТНО БОЛЬШЕ НУЛЯ — иначе мутация, после
 *      которой ничто не зеленеет, прошла бы незамеченной, а перебор остался бы
 *      зелёным, доказав пустоту. Роды считаются И ПО ПРИЗНАКУ ПРОВЕРОК: без
 *      этого мутация, после которой ни один вход не даёт нужной пары, оставила
 *      бы пункты 5 и 6 вакуумными (они проверяют только то, что нашли).
 *
 * СЧЁТНОЕ УТВЕРЖДЕНИЕ ЖИВЁТ В КАЖДОМ ТЕСТЕ, А НЕ ОДНО НА ФАЙЛ (круг починок
 * Ф-6). Общий счётчик модуля читал накопленное ПРЕДЫДУЩИМИ тестами: запуск
 * одного теста через `--test-name-pattern` давал ЛОЖНОЕ падение «входов всего
 * 0», а мутация, убившая зелёные строки в одном разделе, тонула в сумме
 * остальных. Теперь у каждого раздела свой счёт и свои пороги — и порядок
 * тестов больше ничего не значит.
 */

