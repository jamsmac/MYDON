type Свидетельства = "есть" | "нет" | "вход не прочитан";

/**
 * Что известно о проверках (`unavailableRow`): моменты во всех формах, ОБА
 * пересчёта свидетельств и словесное «не знаем».
 *
 * `null` из `МОМЕНТЫ` заменён ответами о свидетельствах намеренно (Ф-1):
 * именно на нём заглушка и врала — «не прочитали журнал» ехало на экран как
 * «не запускался». `undefined` под видом `Date` остаётся: пояса файла держат и
 * его. Пересчётов ДВА, а не один: ноль свидетельств — единственный вход, где
 * «не запускался» законно, и без ненулевого соседа починка «всегда не знаем»
 * прошла бы зелёной.
 */
const СВЕДЕНИЯ: readonly Форма<СведенияОПроверке>[] = [
  ...МОМЕНТЫ.filter((м): м is Форма<Date> => м.значение !== null),
  { имя: "свидетельств 0", значение: { свидетельств: 0 } },
  { имя: "свидетельств 3", значение: { свидетельств: 3 } },
  { имя: "не знаем", значение: "не знаем" },
];

/**
 * Что во входе заглушки известно о проверках.
 *
 * Момент в любой форме, кроме отсутствующей, — свидетельство: даже
 * нечитаемый говорит, что производитель что-то отдал, то есть проверка была.
 * Пересчёт — свидетельство, когда он ненулевой, и «нет», когда нулевой: ноль
 * здесь — ответ вызывающего, который искал и не нашёл. «Не знаем» — вход не
 * прочитан. `undefined` под видом `Date` — не ответ вызывающего, а его
 * отсутствие: утверждать по нему нечего, и это тоже «вход не прочитан».
 */
function свидетельстваЗаглушки(сведения: СведенияОПроверке): Свидетельства {
  if (сведения === "не знаем") return "вход не прочитан";
  if (сведения instanceof Date) return "есть";
  const пересчёт = (сведения as { свидетельств?: number } | undefined)?.свидетельств;
  if (пересчёт === undefined) return "вход не прочитан";
  return пересчёт > 0 ? "есть" : "нет";
}

/** Свидетельство есть — «есть», иначе «нет» (вход прочитан). */
function прочитано(свидетельство: boolean): Свидетельства {
  return свидетельство ? "есть" : "нет";
}

