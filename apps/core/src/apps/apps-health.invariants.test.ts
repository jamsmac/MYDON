/**
 * Что насчитал ОДИН раздел перебора: счётчики живут внутри своего теста.
 *
 * `неЗапускался` и `неЗнаем` — про признак проверок, а не про состояние
 * строки: утверждение «проверок не было» и скромное «когда проверяли —
 * неизвестно» обязаны рождаться ОБА, иначе починка в любую сторону («всегда не
 * знаем», «всегда утверждаем») прошла бы зелёной.
 */
type Счёт = {
  всего: number;
  зелёных: number;
  сломано: number;
  неОценить: number;
  неЗапускался: number;
  неЗнаем: number;
};
const новыйСчёт = (): Счёт => ({
  всего: 0,
  зелёных: 0,
  сломано: 0,
  неОценить: 0,
  неЗапускался: 0,
  неЗнаем: 0,
});

/**
 * Раздел перебора не пуст: входов и строк каждого рода не меньше обещанного.
 *
 * ПОРОГИ — ПОРЯДОК ВЕЛИЧИНЫ, А НЕ ЧИСЛО (с большим запасом вниз от факта):
 * точное совпадение пришлось бы править при каждом новом варианте входа, и его
 * правили бы не глядя. Ноль в ожиданиях — это тоже утверждение («здесь такой
 * строки не бывает»), поэтому проверяется равенством, а не пропускается.
 */
function неПусто(счёт: Счёт, порог: Счёт, раздел: string): void {
  for (const род of ["всего", "зелёных", "сломано", "неОценить", "неЗапускался", "неЗнаем"] as const) {
    const было = счёт[род];
    const надо = порог[род];
    const факт = `${раздел}: ${род} ${было} при пороге ${надо} (весь счёт: ${JSON.stringify(счёт)})`;
    if (надо === 0) assert.equal(было, 0, `${факт} — таких строк тут быть не должно`);
    else assert.ok(было >= надо, `${факт} — перебор доказывает пустоту`);
  }
}

/**
 * Одна строка перебора под всеми утверждениями сразу.
 *
 * Описание входа собирается ЗАРАНЕЕ и передаётся строкой: упавший перебор без
 * него сообщает «где-то в 53 тысячах входов», то есть не сообщает ничего.
 */
function проверить(
  счёт: Счёт,
  описание: string,
  вызов: () => HealthRow,
  свидетельства: Свидетельства,
): void {
  счёт.всего += 1;
  let строка: HealthRow;
  try {
    строка = вызов();
  } catch (ошибка) {
    // Бросок из ЧИСТЫХ ПРАВИЛ — это 500 на весь `/apps/health`: они вызываются
    // вне `попытка`, и вместо строки «оценить нечем» гаснет весь экран.
    assert.fail(`${описание}: правила бросили ${String(ошибка)}`);
  }

  if (строка.state === "ok") {
    счёт.зелёных += 1;
    assert.notEqual(
      строка.lastCheckedAt,
      null,
      `${описание}: зелёная строка «${строка.summary}» без времени проверки`,
    );
  }
  if (строка.state === "bad") счёт.сломано += 1;
  if (строка.state === "unknown") счёт.неОценить += 1;

  // НЕВОЗМОЖНАЯ ПАРА (Ф-1): момент известен, а о проверках «не знаем». Пару
  // собирают два места (база `row` и `сПроверкой`), и разойтись им нечем ровно
  // до первой новой ветки — поэтому утверждение стоит здесь, на всех входах.
  if (!строка.checksKnown) {
    счёт.неЗнаем += 1;
    assert.equal(
      строка.lastCheckedAt,
      null,
      `${описание}: «о проверках не знаем» при известном моменте — момент и есть знание`,
    );
  }

  // УТВЕРЖДЕНИЕ О МИРЕ ТРЕБУЕТ ДОКАЗАТЕЛЬСТВА (К-1). Пара «`checksKnown: true`
  // + момента нет» читается экраном как «не запускался», и она законна ровно
  // там, где вход прочитан и свидетельств проверок в нём нет ни одного.
  // Обратного утверждения к паре выше не было — и перебор оставался зелёным на
  // дефекте: «отказов подряд 3 · не запускался» он кормил правилам сам.
  if (строка.checksKnown && строка.lastCheckedAt === null) {
    счёт.неЗапускался += 1;
    assert.equal(
      свидетельства,
      "нет",
      `${описание}: строка «${строка.summary}» утверждает «проверок не было», ` +
        `хотя во входе — «${свидетельства}»: это ложь о работающем или непрочитанном источнике`,
    );
  }

  // СКРОМНОСТЬ ТОЖЕ ТРЕБУЕТ ПРИЧИНЫ (десятый круг починок, Ф-2). Пара
  // «`checksKnown: false` + момента нет» законна ровно там, где во входе есть
  // свидетельство (проверки были, назвать нечем) либо вход не прочитан. Ноль
  // свидетельств по ПРОЧИТАННОМУ входу обязан стать утверждением «не
  // запускался»: иначе лишний признак свидетельства (мутация «остаток потолка
  // — тоже вызов») или лишний статус в счёте закрытых (мутация «`pending` —
  // тоже закрытие») переводили бы строки из утверждения в «не знаем» молча,
  // и построчно этого не ловил никто.
  if (!строка.checksKnown && строка.lastCheckedAt === null) {
    assert.notEqual(
      свидетельства,
      "нет",
      `${описание}: строка «${строка.summary}» отвечает «о проверках не знаем», ` +
        "хотя вход прочитан и свидетельств в нём ноль — правила нашли свидетельство там, где его нет",
    );
  }

  const моменты: readonly [string, string | null][] = [
    ["lastCheckedAt", строка.lastCheckedAt],
    ["at", строка.at ?? null],
  ];
  for (const [поле, значение] of моменты) {
    if (значение === null) continue;
    assert.ok(
      Number.isFinite(new Date(значение).getTime()),
      `${описание}: в ${поле} уехало «${значение}» — это не момент`,
    );
  }

  const тексты: readonly [string, string][] = [
    ["summary", строка.summary],
    ["detail", строка.detail ?? ""],
  ];
  for (const [поле, текст] of тексты) {
    // `NaN` в тексте — след того же битого момента: «бот отвечает NaN мин
    // назад» и «самой старой NaN ч» уже случались.
    assert.doesNotMatch(текст, /NaN|Invalid Date/, `${описание}: в ${поле} утёк мусор — «${текст}»`);
  }
}

