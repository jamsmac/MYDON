/**
 * ISO-момент, только если дата ЧИТАЕТСЯ; иначе `null`.
 *
 * ТРЕТЬЯ ЗАЩИТА ЭТОГО СРЕЗА ДАННЫХ, рядом с `разобрать` (ISO-строка на входе)
 * и `дата` службы (значение СУБД). Закрывает последний вход, где `Date`
 * приезжает УЖЕ СОБРАННЫМ и никем не проверенным: моменты прогонов собирает
 * `rowFromRaw` (`routines/runs.service.ts`) выражением
 * `startedAt: d(r.started_at)!` — `new Date(строка)` без проверки на
 * конечность и с `!` поверх. Нечитаемый `started_at` дал бы `Invalid Date`, а
 * `toISOString()` на ней бросает `RangeError` — ПРЯМО ИЗ ЧИСТЫХ ПРАВИЛ,
 * которые вызываются вне `попытка`, то есть 500 на весь `/apps/health`.
 *
 * ВИТРИНА ОБЯЗАНА ОТДАТЬ СТРОКУ, А НЕ ПОГАСИТЬ ЭКРАН — ровно для этого
 * существует `unavailableRow`, и было бы издевательством, если бы срез,
 * добавивший второй момент, уронил экран целиком там, где раньше строка
 * молча выживала. Настоящее лечение стоит на границе (`последниеПрогоны`
 * отбрасывает нечитаемый прогон, как `дата` — битое значение СУБД); эта
 * функция — пояс на случай следующего источника моментов.
 */
function исо(момент: Date | null | undefined): string | null {
  if (момент === null || момент === undefined) return null;
  return Number.isFinite(момент.getTime()) ? момент.toISOString() : null;
}

/**
 * Момент, только если он ЧИТАЕТСЯ; иначе `null` — «момента нет».
 *
 * ЕДИНОЕ ПРАВИЛО ФАЙЛА ДЛЯ ПЛОХОГО ВРЕМЕНИ: нечитаемое = отсутствующее.
 * `разобрать` так поступает с ISO-строкой, `дата` службы — со значением СУБД;
 * здесь то же для `Date`, который приехал УЖЕ СОБРАННЫМ и никем не
 * проверенным (`rowFromRaw`: `startedAt: d(r.started_at)!`).
 *
 * ПОЧЕМУ НОРМАЛИЗАЦИЯ, А НЕ ОТДЕЛЬНАЯ ФОРМУЛИРОВКА «не читается» (в отличие от
 * моделей, где она есть). У модели на руках ИСХОДНАЯ строка ledger — её можно
 * показать владельцу. Здесь исходного текста нет вовсе: `Invalid Date` о себе
 * не рассказывает ничего, и «прогон был, но когда — не скажу» ничем не
 * полезнее честного «прогонов нет». Зато уравнивание закрывает вход в зелёную
 * ветку: `ok` «последний прогон прошёл» без времени проверки становится
 * недостижим ПО ПОСТРОЕНИЮ, а не по договорённости со службой.
 */
function читаемыйМомент(момент: Date | null | undefined): Date | null {
  if (момент === null || момент === undefined) return null;
  return Number.isFinite(момент.getTime()) ? момент : null;
}

/** Прогон, момент которого читается; иначе `null` — «прогона нет» (см. выше). */
function сЧитаемымПрогоном<T extends { lastRun: MonitorRunLite | null }>(input: T): T {
  return читаемыйМомент(input.lastRun?.at) === null && input.lastRun !== null
    ? { ...input, lastRun: null }
    : input;
}

/**
 * Вход с ЧИТАЕМЫМ порогом молчания; нечитаемый — «порога нет».
 *
 * ТО ЖЕ ЕДИНОЕ ПРАВИЛО ФАЙЛА, что у `сЧитаемымПрогоном`: нечитаемое =
 * отсутствующее. `silentAfter` — операнд ПОРОГОВОГО сравнения
 * (`now > silentAfter`), а сравнение с `NaN` всегда ложно, поэтому битый момент
 * молча снимал правило молчания. Достижимость через службу сегодня закрыта
 * (`nextOccurrences` со своим `try/catch`), это пояс на следующего
 * производителя моментов — тот же статус, что у `исо`.
 */
function сЧитаемымПорогом<T extends { silentAfter: Date | null }>(input: T): T {
  const порог = читаемыйМомент(input.silentAfter);
  return порог === input.silentAfter ? input : { ...input, silentAfter: порог };
}

/**
 * Момент БЫЛ, но не читается — то есть производитель отдал мусор.
 *
 * ОТЛИЧАЕТСЯ ОТ `читаемыйМомент` ОТВЕТОМ НА ВОПРОС «ПОЧЕМУ МОМЕНТА НЕТ», и для
 * ПОРОГОВЫХ моментов это разные новости. У моментов прогонов `null` и мусор
 * лечатся одинаково («прогонов нет»), поэтому правила их уравнивают. А у
 * `silentAfter` и `oldestPendingAt` `null` — ЗАКОННЫЙ штатный случай:
 * «расписания нет», «неразобранных доставок нет». Уравняй с ним мусор — и
 * правило порога честно пропускается, а строка остаётся зелёной: проверено
 * исполнением собранного `dist` — `Invalid Date` в `silentAfter` давал `ok`
 * «последний прогон прошёл» над монитором, молчащим 30 часов, ровно как `null`.
 * Значит, одной нормализации мало, и битый момент надо ещё и назвать.
 */
function битыйМомент(момент: Date | null | undefined): boolean {
  return момент !== null && момент !== undefined && читаемыйМомент(момент) === null;
}

/** Почему зелёное недоказуемо — по одной формулировке на пороговый момент. */
const ПОРОГ_МОЛЧАНИЯ_НЕ_ЧИТАЕТСЯ =
  "момент планового запуска не читается — судить о молчании монитора нечем";
const МОМЕНТ_ЗАСТОЯ_НЕ_ЧИТАЕТСЯ =
  "момент самой старой неразобранной доставки не читается — судить о застое очереди нечем";

/**
 * Битый пороговый момент ГАСИТ ЗЕЛЁНОЕ, но не спорит с плохим.
 *
 * ПОВЕРХ ГОТОВОГО ВЕРДИКТА, ПО ТОЙ ЖЕ ПРИЧИНЕ, ЧТО И `сПроверкой`: факт «порог
 * приехал мусором» ОДИН на все ветки правил, а повторённый в каждой зелёной
 * ветке он потерялся бы на первой же новой (у учёта их три: `retired`,
 * «сходится», и это не считая порядка). Гасится ровно `ok`: `bad` и `unknown`
 * называют поломку ТОЧНЕЕ, и подменять «расхождений 12» на «оценить нечем» было
 * бы потерей диагноза.
 *
 * ИМЕННО `unknown`, А НЕ `bad`. «Монитор молчит» и «очередь не разбирается» —
 * утверждения, которых мы доказать не можем: порог не прочитан, и сколько
 * времени прошло, неизвестно. Зато «оценить нечем» — ровно то состояние,
 * которое этот срез и придумал для отсутствующих свидетельств (Р-4), и оно не
 * зелёное. Момент проверки при этом остаётся: он берётся из другого поля, и
 * «когда проверяли» мы знаем.
 */
function безЗелёногоНаБитомМоменте(строка: HealthRow, причина: string | null): HealthRow {
  if (причина === null || строка.state !== "ok") return строка;
  return {
    ...строка,
    state: "unknown",
    summary: `здоровье не оценить: ${причина}`,
    detail:
      `правила отдали бы «${строка.summary}»: сравнение с нечитаемым моментом всегда ложно, ` +
      "поэтому порог молча не срабатывает. Чинить надо источник момента, а не строку",
  };
}

function row(
  face: FaceMeta,
  state: HealthState,
  summary: string,
  detail?: string,
  at?: Date,
): HealthRow {
  const событие = исо(at);
  return {
    key: face.key,
    title: face.title,
    state,
    summary,
    href: face.href,
    // База — «проверок не знаем»; момент навешивает `сПроверкой` поверх готовой
    // строки. Аргументом сюда его тащить нельзя: вызовов `row(...)` в файле
    // больше тридцати, и момент разъехался бы по ветвям ровно так, как
    // разъехался `at` (у `молчаливыйИсточник` аргумента `at` нет вовсе).
    lastCheckedAt: null,
    ...(detail !== undefined && detail !== "" ? { detail } : {}),
    ...(событие !== null ? { at: событие } : {}),
  };
}

/**
 * Момент последней проверки — ПОВЕРХ готового вердикта.
 *
 * У одного источника момент проверки ОДИН на все ветки правил: выключенный
 * монитор, молчащий, упавший и прошедший проверялись в один и тот же миг — в
 * свой последний прогон. Вердикт при этом у каждой ветки свой. Поэтому момент
 * считается один раз на входе и накладывается на результат, а не повторяется в
 * каждой ветке: повторённый, он потерялся бы там, где сегодня теряется `at`.
 */
function сПроверкой(строка: HealthRow, проверено: Date | null): HealthRow {
  const момент = исо(проверено);
  return момент === null ? строка : { ...строка, lastCheckedAt: момент };
}

/**
 * Позднейший из известных моментов; ни одного не известно — `null`.
 *
 * ПОЗДНЕЙШИЙ, А НЕ ПЕРВЫЙ ПО СПИСКУ — в этом отличие от `ourvendAt`, который
 * отдаёт предпочтение последнему УСПЕХУ. «Когда проверяли» — это максимум: при
 * серии отказов последний успех недельной давности назвал бы проверкой прошлую
 * неделю, хотя сбор запускается каждые три часа и каждый раз падает.
 *
 * ЭКСПОРТИРУЕТСЯ, ЧТОБЫ ТАКОЙ ФУНКЦИИ БЫЛО РОВНО ОДНА: служба
 * (`apps-health.service.ts`) держала свою копию под именем `позднее` над
 * значениями СУБД, и второй «максимум двух дат» в том же срезе — начало
 * расхождения.
 */
export function позднееИз(a: Date | null | undefined, b: Date | null | undefined): Date | null {
  const x = a ?? null;
  const y = b ?? null;
  if (x === null) return y;
  if (y === null) return x;
  return y.getTime() > x.getTime() ? y : x;
}

/**
 * ЧТО СЧИТАЕТСЯ ПРОВЕРКОЙ У КАЖДОГО ИСТОЧНИКА — шесть ответов рядом.
 *
 * Вопрос один («когда этот источник в последний раз проверялся»), ответ у
 * каждого свой, и врозь эти ответы разъехались бы так же, как разъехались три
 * словаря состояний в панели. Ниже — экспортируемые входы; правила оценки
 * остались нетронутыми в приватных `вердикт*` ниже по файлу.
 */

/**
 * Строка монитора + момент последней проверки.
 *
 * ПРОВЕРКА МОНИТОРА — ЭТО ЕГО ПРОГОН. Другого мерила у Core нет: источник о
 * себе не рассказывает, известно ровно то, что записал последний тик. Прогонов
 * нет — проверок не было ни разу, и `null` здесь не заглушка, а факт.
 *
 * МОМЕНТ ЖИВЁТ И ТАМ, ГДЕ НЕТ `at`. Выключенный монитор и монитор вне снимка
 * отдают строку без `at` (`молчаливыйИсточник` такого аргумента не принимает),
 * но проверялись они в свой последний прогон.
 */
export function rowFromMonitor(face: FaceMeta, input: MonitorRowInput): HealthRow {
  const вход = сЧитаемымПрогоном(сЧитаемымПорогом(input));
  return безЗелёногоНаБитомМоменте(
    сПроверкой(вердиктМонитора(face, вход), вход.lastRun?.at ?? null),
    битыйМомент(input.silentAfter) ? ПОРОГ_МОЛЧАНИЯ_НЕ_ЧИТАЕТСЯ : null,
  );
}

/**
 * Сбор OurVend + момент последней проверки.
 *
 * ПОЗДНЕЙШИЙ ИЗ ДВУХ ИЗВЕСТНЫХ МОМЕНТОВ, потому что у каждого свой пробел.
 * Отчёт `/ourvend/health` знает только УСПЕХИ (`lastSuccessAt`): при серии
 * отказов сбор тикает каждые три часа и каждый раз падает — проверки идут, а
 * успеха нет неделю. Журнал прогонов (`lastRun.at`) знает и отказы, но
 * чистится ретенцией. Число прогонов (`runs`) момента не несёт вовсе, поэтому
 * судить по нему нечем.
 */
export function rowFromOurvendSync(face: FaceMeta, input: OurvendSyncInput): HealthRow {
  const вход = сЧитаемымПрогоном(input);
  return сПроверкой(вердиктСбора(face, вход), проверкаСбора(вход));
}

/**
 * Учётный снимок OurVend + момент последней проверки.
 *
 * ТОЛЬКО ТИК МОНИТОРА, И БОЛЬШЕ ВЗЯТЬ НЕОТКУДА. В отчёте учёта нет ни одного
 * момента: `snapshotStale` — готовый вердикт, `salesLagShownH` — часы, да ещё
 * ОКРУГЛЁННЫЕ ДЛЯ ПОКАЗА. Вычесть лаг из `now` значило бы выдумать момент с
 * точностью до часа и назвать выдумку проверкой.
 */
export function rowFromOurvendAccounting(face: FaceMeta, input: OurvendAccountingInput): HealthRow {
  const вход = сЧитаемымПрогоном(сЧитаемымПорогом(input));
  return безЗелёногоНаБитомМоменте(
    сПроверкой(вердиктУчёта(face, вход), вход.lastRun?.at ?? null),
    битыйМомент(input.silentAfter) ? ПОРОГ_МОЛЧАНИЯ_НЕ_ЧИТАЕТСЯ : null,
  );
}

/**
 * Очередь доставок + момент последней проверки.
 *
 * ПРОВЕРКА — ПОСЛЕДНЯЯ ЗАКРЫТАЯ ДОСТАВКА, любым исходом: ушла, пропущена,
 * отказала. Каждая закрытая строка — проход диспетчера, то есть настоящая
 * попытка достучаться до Notion. Пропуск — тоже проход («ключа нет»), и рядом
 * с «источник не настроен» он говорит владельцу важное: диспетчер жив.
 *
 * `oldestPendingAt` В ПРОВЕРКУ НЕ ГОДИТСЯ, хотя дата у него есть: это момент
 * СОЗДАНИЯ строки, которую мы положили сами. Вставшая очередь выглядела бы
 * «проверенной пять минут назад» ровно потому, что в неё подкладывают новые
 * доставки, которые никто не разбирает.
 *
 * ТОТ ЖЕ ФАКТ СПРАШИВАЕТ И ВЕРДИКТ (`закрытиеДоставки`): нет момента закрытия
 * — нет и свидетельства, что доставщик ходил, поэтому строка отдаёт
 * «не оценить», а не «в порядке». Зелёной без отметки времени она быть не
 * может по построению.
 */
export function rowFromOutbox(face: FaceMeta, input: OutboxRowInput): HealthRow {
  // ВСЕ ЧЕТЫРЕ МОМЕНТА ОЧЕРЕДИ НОРМАЛИЗУЮТСЯ ЗДЕСЬ, НА ОДНОЙ ГРАНИЦЕ.
  //
  // Возраст самой старой неразобранной доставки — такой же операнд порога, как
  // `silentAfter` у монитора, и `null` здесь тоже законный случай
  // («неразобранных нет»). Поэтому нечитаемый момент уравнивается с
  // отсутствующим, а зелёное над ним гасится ниже: производитель, отдавший
  // мусор вместо `null`, утверждает, что неразобранные доставки ЕСТЬ, — только
  // не говорит, с каких пор.
  //
  // Моменты закрытий (`lastSentAt`/`lastSkippedAt`/`lastFailedAt`) нормализуются
  // рядом, потому что вердикт судит ими ПОРЯДОК исходов через `позже`, и там
  // они спрашивались СЫРЫМИ, в отличие от `закрытиеДоставки`. Два следствия,
  // оба нашёл перебор форм (`apps-health.invariants.test.ts`): `undefined`
  // вместо момента ронял правила `TypeError`-ом на `a.getTime()` (то есть 500 на
  // весь `/apps/health`), а `Invalid Date` в момент успеха делал СВЕЖИЙ отказ
  // «несвежим» — сравнение с `NaN` ложно в обе стороны, и строка не краснела.
  const вход: OutboxRowInput = {
    ...input,
    oldestPendingAt: читаемыйМомент(input.oldestPendingAt),
    lastSentAt: читаемыйМомент(input.lastSentAt),
    lastSkippedAt: читаемыйМомент(input.lastSkippedAt),
    lastFailedAt: читаемыйМомент(input.lastFailedAt),
  };
  return безЗелёногоНаБитомМоменте(
    сПроверкой(вердиктДоставок(face, вход), закрытиеДоставки(вход)),
    битыйМомент(input.oldestPendingAt) ? МОМЕНТ_ЗАСТОЯ_НЕ_ЧИТАЕТСЯ : null,
  );
}

/**
 * Heartbeat бота + момент последней проверки.
 *
 * ЗДЕСЬ ПРОВЕРКА И СОБЫТИЕ — ОДНО И ТО ЖЕ: сигнал «я жив» и есть проверка
 * поллера, и `lastCheckedAt` совпадает с `at`. Совпадение записано намеренно —
 * иначе следующий автор пойдёт искать боту второй источник времени.
 */
export function rowFromHeartbeat(face: FaceMeta, input: HeartbeatRowInput): HealthRow {
  // Нечитаемый момент сигнала — это «сигнала не было», а не «бот отвечает NaN
  // мин назад»: возраст ушёл бы в NaN, сравнение с порогом дало бы `false`, и
  // строка зазеленела бы без времени и с мусором в тексте.
  const lastAt = читаемыйМомент(input.lastAt);
  return сПроверкой(вердиктСигнала(face, { ...input, lastAt }), lastAt);
}

/**
 * Ledger моделей + момент последней проверки.
 *
 * ПРОВЕРКА — ПОСЛЕДНИЙ ЗАВЕРШЁННЫЙ ВЫЗОВ, и отказавший тоже: попытка позвать
 * провайдера состоялась, а её исход строка уже цитирует. Битую дату
 * отбрасываем тем же `разобрать`, что и вердикт: она ушла бы в `toISOString()`
 * и уронила бы ВЕСЬ ответ. Монитор ledger не ответил (`monitoring === null`) —
 * о вызовах не известно ничего, и это `null`.
 */
export function rowFromLlm(face: FaceMeta, input: LlmRowInput): HealthRow {
  return сПроверкой(вердиктМоделей(face, input), моментВызова(input.monitoring) ?? null);
}

/**
 * Момент последнего завершённого вызова — РАЗОБРАННЫЙ; `undefined` — вызовов не
 * было либо дата не читается.
 *
 * ОДНА ФУНКЦИЯ НА ДВА ВОПРОСА, третий раз в файле (ср. `закрытиеДоставки`,
 * `проверкаСбора`). Гард вердикта раньше спрашивал СЫРОЕ поле
 * (`latestCompletedAt === null`), а обёртка — разобранное, и нераспознанная
 * дата проходила гард насквозь: строка отдавала `ok` «вызовы проходят» БЕЗ
 * времени проверки. Теперь оба спрашивают один разбор, и разойтись им нечем.
 */
function моментВызова(m: LlmMonitoringLite | null): Date | undefined {
  return разобрать(m?.latestCompletedAt ?? null);
}

/**
 * Источник, о котором нечего спрашивать: снимка нет или монитор выключен.
 *
 * ВОЗВРАЩАЕТ `unknown`, А НЕ `ok`, И СТОИТ ПЕРВЫМ ПРАВИЛОМ. Выключенный
 * монитор не падает и не жалуется — у него просто нет прогонов, и «ошибок
 * нет» о нём было бы правдой формы и ложью смысла. Причина берётся из снимка:
 * «выключен» и «не настроен» чинят по-разному.
 */
function молчаливыйИсточник(
  face: FaceMeta,
  snapshotPublished: boolean,
  monitor: MonitorSnapshotLite | null,
): HealthRow | null {
  if (monitor === null) {
    return snapshotPublished
      ? row(
          face,
          "unknown",
          "монитор не заявлен в снимке расписаний",
          "слой агентов о нём не сообщал: монитор снят из кода или на сервере работает старая версия агентов",
        )
      : row(
          face,
          "unknown",
          "агенты ещё не отчитывались: снимка расписаний в Core нет",
          "неизвестно даже, включён ли монитор — слой агентов ни разу не публиковал расписания",
        );
  }
  if (monitor.enabled) return null;
  if (monitor.reason === "no_credentials") {
    return row(
      face,
      "unknown",
      "источник не настроен: нет учётных данных",
      monitor.disabledText ?? "монитор не заводится, пока в окружении агентов нет учётной записи источника",
    );
  }
  if (monitor.reason === "off") {
    return row(
      face,
      "unknown",
      "монитор выключен в настройках",
      monitor.disabledText ?? "расписание снято владельцем или не принято при старте агентов",
    );
  }
  return row(face, "unknown", "монитор выключен", monitor.disabledText ?? "снимок расписаний не назвал причину");
}

/** Ярлык исхода словами общего словаря (`@mydon/shared`), а не второй формулировкой. */
function исходЯрлык(outcome: string): string {
  return isRunOutcome(outcome) ? RUN_OUTCOME_LABELS[outcome] : outcome;
}

/** Итог прогона одной фразой — для `detail`, где рядом не стоит слово «прогон». */
function исходСловами(run: MonitorRunLite): string {
  return `последний прогон — ${исходЯрлык(run.outcome)}: ${run.reason}`;
}

/**
 * Строка обычного монитора: снимок расписаний + последний прогон.
 *
 * ПОРЯДОК ПРАВИЛ: выключен → прогонов нет → молчит → упал → прошёл. «Молчит»
 * стоит ВЫШЕ исхода сознательно: `failedStreak = 0` держится вечно, если крон
 * перестал ЗАПУСКАТЬСЯ — он не падает, а молчит, и зелёная строка спокойно
 * стоит над мёртвым расписанием.
 */
function вердиктМонитора(face: FaceMeta, input: MonitorRowInput): HealthRow {
  const молчит = молчаливыйИсточник(face, input.snapshotPublished, input.monitor);
  if (молчит !== null) return молчит;

  const run = input.lastRun;
  if (run === null) {
    return row(face, "unknown", "здоровье не оценить: монитор не запускался или журнал прогонов пуст");
  }
  if (input.silentAfter !== null && input.now.getTime() > input.silentAfter.getTime()) {
    return row(
      face,
      "bad",
      "монитор молчит: пропущено больше одного планового запуска",
      исходСловами(run),
      run.at,
    );
  }
  if (run.outcome === "failed") {
    return row(face, "bad", "последний прогон упал", run.reason, run.at);
  }
  if (run.outcome === "executed") {
    return row(face, "ok", "последний прогон прошёл", run.reason, run.at);
  }
  // `approval_requested` и `skipped` мониторы не пишут (`journaledMonitor`
  // знает только `executed`/`failed`), поэтому чужой исход — это не «плохо»
  // и не «хорошо», а «мы такого не ждали».
  return row(face, "unknown", `исход последнего прогона — ${исходЯрлык(run.outcome)}: оценить нечем`, run.reason, run.at);
}

/**
 * Дата из ISO-строки, если она вообще дата: битая отбрасывается, а не роняет ответ.
 *
 * РИСК НА БУДУЩЕЕ: У `lastSuccessAt` В СИСТЕМЕ ДВА РАЗБОРЩИКА. Здесь голый
 * `new Date`, а все остальные читатели того же поля (`rawStaleHours` в
 * `ourvend/sync-runs.ts`, правила, бот) разбирают его `tashkentInstant`.
 * Сегодня расхождения нет: продюсер (`ourvend-health.service.ts`) всегда
 * отдаёт `toISOString()`, то есть строку С ЗОНОЙ, и оба разборщика читают её
 * одинаково. Но если поле приедет в форме СУБД («YYYY-MM-DD HH:mm:ss») или
 * голой датой, `tashkentInstant` подставит +05, а `new Date` — зону процесса
 * либо UTC, и два ответа молча разойдутся НА ПЯТЬ ЧАСОВ. В этом репозитории
 * сдвиг на пять часов уже случался (247 строк инкассаций), поэтому: меняешь
 * форму, которую отдаёт продюсер, — приходи сюда, а не только в `staleHours`.
 */
function разобрать(iso: string | null): Date | undefined {
  if (iso === null) return undefined;
  const d = new Date(iso);
  return Number.isFinite(d.getTime()) ? d : undefined;
}

/** Момент, который строка про OurVend описывает: последний успех, иначе тик монитора. */
function ourvendAt(lastSuccessAt: string | null, lastRun: MonitorRunLite | null): Date | undefined {
  return разобрать(lastSuccessAt) ?? lastRun?.at;
}

/**
 * Момент последней ПРОВЕРКИ сбора: позднейший из читаемого успеха и тика
 * монитора; `null` — ни одного.
 *
 * ОДНА ФУНКЦИЯ НА ДВА ВОПРОСА — тот же приём, что у `закрытиеДоставки`. Её
 * спрашивает и обёртка («когда проверяли»), и зелёная ветка вердикта («имеем ли
 * право говорить „данные свежие“»). Врозь они уже расходились: вердикт
 * доказывал свежесть по `staleHoursRaw`, а обёртка искала момент в ДРУГОМ поле
 * (`lastSuccessAt`), и вход `{ lastSuccessAt: null, staleHoursRaw: 1 }` при
 * пустом журнале прогонов давал зелёную строку БЕЗ времени. Через HTTP такой
 * вход сегодня не приезжает — служба считает `staleHoursRaw` из того же
 * `lastSuccessAt` (`rawStaleHours`), — но это согласованность в двух модулях
 * отсюда, то есть «по договорённости». Гард ниже делает её «по построению».
 */
function проверкаСбора(input: OurvendSyncInput): Date | null {
  return позднееИз(разобрать(input.health?.lastSuccessAt ?? null), input.lastRun?.at);
}

/**
 * Сбор OurVend: прогоны, серия отказов, застой (R-A2-2).
 *
 * ПОРОГ СРАВНИВАЕТСЯ С `staleHoursRaw`, А НЕ С ПОКАЗАННЫМ ЧИСЛОМ. «5 ч 59 м
 * 49 с» округляются до ровно 6,0, и сравнение по показанному сдвинуло бы
 * границу на 11 секунд раньше настоящей. Источник истины по границе —
 * `rawStaleHours` (`ourvend/sync-runs.ts`), показанное число живёт только в
 * тексте.
 */
function вердиктСбора(face: FaceMeta, input: OurvendSyncInput): HealthRow {
  const молчит = молчаливыйИсточник(face, input.snapshotPublished, input.monitor);
  if (молчит !== null) return молчит;

  const h = input.health;
  if (h === null) {
    return row(face, "unknown", "здоровье не оценить: отчёт OurVend не собрался", undefined, input.lastRun?.at);
  }
  const at = ourvendAt(h.lastSuccessAt, input.lastRun);
  // Ни одного прогона — это третье состояние, а не «ошибок нет»: серия отказов
  // равна нулю просто потому, что сбор ни разу не запускался (цитата бота).
  if (h.runs === 0) {
    return row(face, "unknown", "здоровье не оценить: сбор не запускался или журнал прогонов пуст", undefined, at);
  }
  if (h.failedStreak > 0) {
    return row(
      face,
      "bad",
      `отказов подряд ${h.failedStreak} — сбор стоит, свежих данных нет`,
      input.lastRun !== null ? исходСловами(input.lastRun) : undefined,
      at,
    );
  }
  if (h.staleHoursRaw === null) {
    return row(face, "bad", "сбор стоит — успешных прогонов не было", undefined, at);
  }
  if (h.staleHoursRaw >= h.staleThresholdH) {
    const показ = Math.round(h.staleHoursShown ?? h.staleHoursRaw);
    return row(
      face,
      "bad",
      `сбор стоит ${показ} ч — порог ${h.staleThresholdH} ч`,
      input.lastRun !== null ? исходСловами(input.lastRun) : undefined,
      at,
    );
  }
  // ЗЕЛЁНОЙ БЕЗ ВРЕМЕНИ ПРОВЕРКИ НЕ БЫВАЕТ (срез Д1, Р-Д1-3). «Данные свежие»
  // выше доказано `staleHoursRaw`, а момент проверки живёт в ДРУГИХ полях —
  // читаемом `lastSuccessAt` и тике монитора. Рассогласуй их (битая дата
  // успеха, пустой журнал прогонов) — и строка зазеленела бы, не умея назвать,
  // когда её проверяли, то есть ровно так, как запрещает срез. Гард стоит
  // рядом с правилом, а не в службе за два модуля отсюда.
  if (проверкаСбора(input) === null) {
    return row(
      face,
      "unknown",
      "здоровье не оценить: отчёт называет данные свежими, а момента последнего успеха в нём нет",
      "свежесть посчитана по одному полю отчёта, а когда сбор проверяли — сказать нечем: " +
        "ни читаемого момента успеха, ни прогона в журнале",
    );
  }
  return row(
    face,
    "ok",
    "отказов подряд нет, данные свежие",
    input.lastRun !== null ? исходСловами(input.lastRun) : undefined,
    at,
  );
}

/**
 * Учётный снимок OurVend и сверка с зеркалом.
 *
 * СВЕРКА ЖИВЁТ В ЭТОЙ СТРОКЕ, А НЕ В ОТДЕЛЬНОЙ: сверять есть что ровно тогда,
 * когда этот агент довёз снимок, и «расхождений 0» — это утверждение о его
 * работе. Ноль расхождений БЕЗ СВЕРКИ «сходится» не значит: зелёная галка над
 * несравнёнными сутками — та же ложь, что зелёная галка над нулём прогонов.
 *
 * ПОРЯДОК ПРАВИЛ: выключен → отчёта нет → снимок встал → прогонов нет →
 * молчит → упал → выводы сверки. Первые пять называют поломку точнее любого
 * вывода о сверке, а сама сверка судит о прогоне, которого могло не быть.
 */
function вердиктУчёта(face: FaceMeta, input: OurvendAccountingInput): HealthRow {
  const молчит = молчаливыйИсточник(face, input.snapshotPublished, input.monitor);
  if (молчит !== null) return молчит;

  const h = input.health;
  const at = input.lastRun?.at;
  if (h === null) {
    return row(face, "unknown", "здоровье не оценить: отчёт OurVend не собрался", undefined, at);
  }
  // Вердикт Core, а не сравнение округлённого лага с порогом: `snapshotStale`
  // считается по сырым часам и по ОБЕИМ половинам снимка (продажи и остатки).
  if (h.snapshotStale) {
    const давность =
      h.salesLagShownH === null ? "снимков продаж нет" : `снимок продаж — ${Math.round(h.salesLagShownH)} ч`;
    return row(
      face,
      "bad",
      "учётный снапшот OurVend не обновляется — продажи и остатки стоят",
      давность,
      at,
    );
  }
  if (input.lastRun === null) {
    return row(face, "unknown", "здоровье не оценить: монитор не запускался или журнал прогонов пуст");
  }
  // МОЛЧАНИЕ МОНИТОРА — ВЫШЕ ЛЮБОГО ВЫВОДА О СВЕРКЕ (круг починок, C-5). Ниже
  // «расхождений 0» и «снимок свежий» — утверждения о РАБОТЕ этого монитора, а
  // если он не запускается, они описывают позавчерашний день. То же правило и
  // тот же порог (второй пропущенный тик), что у `rowFromMonitor`.
  if (input.silentAfter !== null && input.now.getTime() > input.silentAfter.getTime()) {
    return row(
      face,
      "bad",
      "монитор молчит: пропущено больше одного планового запуска",
      исходСловами(input.lastRun),
      at,
    );
  }
  // ПОСЛЕДНИЙ ПРОГОН УПАЛ — «сломано»: то же правило и то же место цепочки,
  // что у `rowFromMonitor` (круг починок 2, Ф-1). Падающий монитор НЕ молчит:
  // он тикает по расписанию и каждый раз падает, поэтому проверка молчания
  // выше его не ловит; `snapshotStale` в штатном откате катовера
  // (`OURVEND_ACCOUNTING_SOURCE=stock`) жёстко `false` по построению, а на
  // сегодняшней проде (`own` + погашенное зеркало, `mode: "retired"`)
  // паритетного пояса нет вовсе. Строка отдавала `ok` «сверка сходится»,
  // цитируя В ТОЙ ЖЕ СТРОКЕ «последний прогон — упал»: зелёная лампа прямо
  // против собственного пояснения.
  //
  // ПОЧЕМУ ИМЕННО ЗДЕСЬ. Выше стоят диагнозы ТОЧНЕЕ («снапшот не
  // обновляется», «монитор молчит») — они называют владельцу конкретную
  // поломку, и падение прогона их не перекрывает. Ниже — выводы сверки, но
  // это утверждения о РАБОТЕ прогона, которого не было: числа паритета
  // описывают предыдущий, успешный проход, а `mode: "retired"` возвращает
  // `ok` вообще без проверок. Поэтому исход прогона решает раньше сверки.
  if (input.lastRun.outcome === "failed") {
    return row(face, "bad", "последний прогон упал", input.lastRun.reason, at);
  }

  const p = h.parity;
  // Зеркало погашено: сверять больше не с чем ШТАТНО, и «не оценить» здесь
  // читалось бы как авария конца катовера (R-FW-P3).
  if (p.mode === "retired") {
    return row(
      face,
      "ok",
      "снимок свежий; сверка с зеркалом завершена — сравнивать больше не с чем",
      исходСловами(input.lastRun),
      at,
    );
  }
  if (p.mismatches > 0) {
    return row(face, "bad", `сверка продаж: расхождений ${p.mismatches}`, исходСловами(input.lastRun), at);
  }
  if (!p.stockOk && p.stockChecked > 0) {
    return row(face, "bad", "сверка остатков: расходится", исходСловами(input.lastRun), at);
  }
  const продажНеСверены = p.checked === 0;
  const остаткиНеСверены = !p.stockOk && p.stockChecked === 0;
  if (продажНеСверены || остаткиНеСверены) {
    const части = [
      продажНеСверены ? "продажи: сверять нечего" : null,
      остаткиНеСверены ? "остатки: снимков за период нет — сверять не по чему" : null,
    ].filter((ч): ч is string => ч !== null);
    return row(
      face,
      "unknown",
      `снимок свежий, но сверка ничего не сравнила (${части.join(" · ")})`,
      "расхождений 0 здесь значит «не с чем сравнивать», а не «сошлось»",
      at,
    );
  }
  return row(
    face,
    "ok",
    `снимок свежий, сверка сходится (пар продаж ${p.checked}, остатков ${p.stockChecked})`,
    исходСловами(input.lastRun),
    at,
  );
}

/**
 * Момент последнего ЗАКРЫТИЯ доставки любым исходом; `null` — ни одна не
 * закрылась.
 *
 * ОДНА ФУНКЦИЯ НА ДВА ВОПРОСА, И ЭТО НЕ СОВПАДЕНИЕ. «Когда источник в
 * последний раз проверялся» (`rowFromOutbox`) и «есть ли вообще свидетельство,
 * что доставщик ходил» (`вердиктДоставок`) — один и тот же факт с двух сторон.
 * Врозь они разъехались бы на первом же новом исходе, и строка снова смогла бы
 * зазеленеть без времени — ровно то, что запрещает Р-Д1-3.
 */
function закрытиеДоставки(input: OutboxRowInput): Date | null {
  // Нормализуем КАЖДЫЙ момент, а не результат: сравнение с `NaN` всегда ложно,
  // поэтому один битый момент в `позднееИз` съел бы читаемый соседний.
  return позднееИз(
    позднееИз(читаемыйМомент(input.lastSentAt), читаемыйМомент(input.lastSkippedAt)),
    читаемыйМомент(input.lastFailedAt),
  );
}

/** Исход `a` случился ПОЗЖЕ исхода `b` (или `b` не случался вовсе)? */
function позже(a: Date | null, b: Date | null): boolean {
  if (a === null) return false;
  return b === null || a.getTime() > b.getTime();
}

/**
 * Очередь доставок наружу (Notion) — по счётчикам `outbox_delivery`.
 *
 * ПУСТАЯ ТАБЛИЦА — НЕ «ОЧЕРЕДЬ РАЗОБРАНА». Ноль строк означает, что в очередь
 * ничего не клали: доставок ещё не было, и оценивать нечего.
 *
 * СЧЁТЧИКИ НАЗЫВАЮТ ЧИСЛА, ВЕРДИКТ ВЫНОСИТ ПОРЯДОК ИСХОДОВ (круг починок, A-2).
 * Таблица бесконечна, и «в ней есть `skipped`» / «в ней есть `dead`» — не
 * утверждения о сегодняшнем дне: первое молчало после первой же успешной
 * доставки, второе краснело вечно после первой же неудачной. Спрашиваем не
 * «бывало ли», а «случилось ли это ПОСЛЕ последнего успеха».
 */
function вердиктДоставок(face: FaceMeta, input: OutboxRowInput): HealthRow {
  const счёт = (status: string): number => input.counts[status] ?? 0;
  const всего = Object.values(input.counts).reduce((a, b) => a + b, 0);
  if (всего === 0) {
    return row(face, "unknown", "доставок ещё не было", "в очереди нет ни одной строки — ни успешной, ни отказавшей");
  }
  const тупик = счёт("dead");
  // `unknown` — исход, при котором мы НЕ ЗНАЕМ, дошла ли запись: повтор мог бы
  // задвоить её на той стороне. Тот же список, по которому будит владельца
  // сторож ledger (индекс `outbox_delivery_alert_terminal_idx`: unknown или dead).
  const неясно = счёт("unknown");
  const пропущено = счёт("skipped");
  const очередь = счёт("pending") + счёт("dispatching");
  const ушло = счёт("sent");
  const хвостПропусков = пропущено > 0 ? ` · пропущено ${пропущено}` : "";
  const итого = `всего строк доставки ${всего}`;

  const части = [
    тупик > 0 ? `в тупике ${тупик}` : null,
    неясно > 0 ? `с неизвестным исходом ${неясно}` : null,
  ].filter((ч): ч is string => ч !== null);
  // Отказ СВЕЖИЙ: после него ни одна доставка не ушла. Старый отказ, за
  // которым доставки пошли, красным быть не должен — но и исчезнуть не может,
  // и ниже он назван в `detail`. `lastSentAt === null` — успехов не было
  // вовсе: тогда отказ свежий по определению, каким бы ни был его момент
  // (страховка от строки без `completed_at`).
  if (части.length > 0 && (input.lastSentAt === null || позже(input.lastFailedAt, input.lastSentAt))) {
    return row(
      face,
      "bad",
      `доставки не дошли: ${части.join(" · ")}${хвостПропусков}`,
      итого,
      input.lastFailedAt ?? input.oldestPendingAt ?? undefined,
    );
  }

  // ОЧЕРЕДЬ, КОТОРУЮ НИКТО НЕ РАЗБИРАЕТ, — ЭТО НЕ «В ПОРЯДКЕ». Диспетчер не
  // падает, а молчит: строки остаются `pending` навсегда, ни один статус не
  // становится плохим, и «в очереди 500» спокойно зеленеет. Та же ловушка, что
  // у замолчавшего крона монитора, и то же лекарство — возраст, а не статус.
  const застряло = input.oldestPendingAt;
  if (застряло !== null && input.now.getTime() - застряло.getTime() > OUTBOX_STUCK_MS) {
    const часов = Math.round((input.now.getTime() - застряло.getTime()) / ЧАС);
    return row(
      face,
      "bad",
      `очередь не разбирается: в ней ${очередь}, самой старой ${часов} ч${хвостПропусков}`,
      `${итого}; доставщик забирает партию раз в проход агентов — час без движения означает, что он не работает`,
      застряло,
    );
  }

  // ПРОПУСКАЮТ СЕЙЧАС — ЭТО «НЕ НАСТРОЕНО», А НЕ «ДОСТАВЛЕНО 0». Диспетчер
  // закрывает доставку статусом `skipped` ровно в одном случае: конфигурации
  // Notion нет (`apps/agents/src/outbox-dispatcher.ts`, «Notion не настроен»).
  // Условие — ПОСЛЕДНИЙ пропуск свежее последнего успеха, а не «пропущено ==
  // всего»: прежнее правило молчало ровно в том случае, ради которого его
  // писали, — когда ключ убрали у уже работавшего источника.
  // `пропущено === всего` остаётся вторым поясом: если у строк почему-то нет
  // `completed_at`, порядок исходов неизвестен, а вывод «не настроен» верен.
  if (пропущено > 0 && (пропущено === всего || позже(input.lastSkippedAt, input.lastSentAt))) {
    return row(
      face,
      "unknown",
      `источник не настроен: доставки пропускаются, пропущено ${пропущено}`,
      "диспетчер закрывает доставку как «пропущена», пока в окружении агентов нет ключа и базы Notion" +
        (ушло > 0 ? `; после последней успешной доставки не ушло ни одной (успешных всего ${ушло})` : ""),
      input.lastSkippedAt ?? input.oldestPendingAt ?? undefined,
    );
  }

  // НИ ОДНА ДОСТАВКА НЕ ЗАКРЫЛАСЬ — «НЕ ОЦЕНИТЬ», А НЕ «В ПОРЯДКЕ» (срез Д1,
  // Р-Д1-3). Строки в очередь положили МЫ: они говорят о нас, а не о Notion, и
  // пока ни одна не закрылась ни одним исходом, свидетельств, что доставщик
  // вообще ходил, нет ни одного. «Доставлено 0, очередь разобрана» здесь — та
  // же ложь, что зелёная галка над нулём прогонов монитора, то есть главный
  // инвариант волны A2: ноль проверок — это `unknown`.
  //
  // ПОЧЕМУ ИМЕННО ЗДЕСЬ, ПОСЛЕДНИМ ПЕРЕД «ОК». Всё, что стоит выше, называет
  // поломку ТОЧНЕЕ и обязано остаться точнее: свежий тупик (даже у строк без
  // `completed_at`), очередь, которую не разбирают, и «источник не настроен»
  // по второму поясу `пропущено === всего`. Это правило забирает ровно тот
  // остаток, который иначе зеленел бы: доставки в очереди есть, а закрытых нет.
  //
  // ЭТО СОСТОЯНИЕ ДОСТИЖИМО И ОДНОРАЗОВО: ретенции у `outbox_delivery` нет,
  // `completed_at` закрытой строки остаётся навсегда, поэтому «закрытых нет»
  // живёт от первой положенной доставки до первой закрытой — первый час
  // свежей установки или только что подключённого назначения. Ровно тот час,
  // когда владельцу важнее всего знать, работает ли доставщик вообще.
  const закрытых = ушло + пропущено + тупик + неясно;
  if (закрытиеДоставки(input) === null) {
    return row(
      face,
      "unknown",
      закрытых === 0
        ? `здоровье не оценить: ни одна доставка ещё не закрылась, в очереди ${очередь}`
        : `здоровье не оценить: у закрытых доставок (${закрытых}) нет момента закрытия`,
      закрытых === 0
        ? `${итого}; строки в очередь положили мы — пока ни одна не закрылась (ни успехом, ни пропуском, ни отказом), ` +
          "о работе доставщика не известно ничего"
        : `${итого}; у строк нет времени закрытия: порядок исходов неизвестен, и судить о свежести доставок нечем`,
      input.oldestPendingAt ?? undefined,
    );
  }

  // Доставки идут. Старые отказы НЕ красят строку, но и не пропадают: запись,
  // не дошедшая до Notion, разбирается вручную, и число обязано остаться на
  // экране — иначе «зелено» означало бы «всё дошло».
  const хвостОтказов =
    части.length > 0 ? `; до последней успешной доставки — ${части.join(" · ")}: разбери вручную` : "";
  return row(
    face,
    "ok",
    (очередь > 0 ? `в очереди ${очередь}, доставлено ${ушло}` : `доставлено ${ушло}, очередь разобрана`) +
      хвостПропусков,
    итого + хвостОтказов,
    input.oldestPendingAt ?? undefined,
  );
}

/**
 * Жив ли Telegram-поллер (Р-5): heartbeat раз в пять минут.
 *
 * Offset опроса живёт в памяти процесса, и если поллер молча упал, в базе об
 * этом не скажет ничто, кроме отсутствия этих событий. Отсутствие событий
 * ВООБЩЕ — «не отчитывался», а не «молчит»: бот мог просто ни разу не
 * запуститься с этой версией.
 */
function вердиктСигнала(face: FaceMeta, input: HeartbeatRowInput): HealthRow {
  if (input.lastAt === null) {
    return row(
      face,
      "unknown",
      "бот ещё не отчитывался: heartbeat в журнале не появлялся",
      "поллер либо не запускался, либо работает версией без heartbeat",
    );
  }
  const возраст = Math.max(0, input.now.getTime() - input.lastAt.getTime());
  const минут = Math.round(возраст / МИНУТА);
  if (возраст > input.intervalMs * BOT_HEARTBEAT_MISS_LIMIT) {
    return row(
      face,
      "bad",
      `бот молчит ${минут} мин — поллер, скорее всего, не работает`,
      `сигнал ждём каждые ${Math.round(input.intervalMs / МИНУТА)} мин`,
      input.lastAt,
    );
  }
  return row(face, "ok", `бот отвечает: последний сигнал ${минут} мин назад`, undefined, input.lastAt);
}

/**
 * Ledger моделей: может ли система вообще звать провайдера.
 *
 * СПИСОК ПОВОДОВ ПОКРАСНЕТЬ — ТОТ ЖЕ, ЧТО У СТОРОЖА `LlmAlertMonitorService`
 * (предохранитель, зависшие резервы, потолок, неверная настройка). Голое
 * число отказов за день в этот список не входит: один 429 от провайдера — не
 * авария, и красить им строку значило бы приучить владельца её не замечать.
 */
function вердиктМоделей(face: FaceMeta, input: LlmRowInput): HealthRow {
  const m = input.monitoring;
  if (m === null) return row(face, "unknown", "здоровье не оценить: монитор ledger не ответил");
  // Момент последнего завершённого вызова — только если он разбирается: битая
  // строка ушла бы в `toISOString()` и уронила бы весь ответ. НИЖЕ ПО ЭТОМУ
  // МОМЕНТУ СУДИТ И ГАРД «вызовов не было», а не по сырому полю: иначе
  // нераспознанная дата проходит его насквозь и зеленит строку без времени.
  const at = моментВызова(m);

  if (!m.meteredEnabled) {
    return row(
      face,
      "unknown",
      "метрируемый маршрут моделей выключен — оценивать нечего",
      "платные вызовы отключены настройкой: ни расхода, ни отказов быть не может",
    );
  }
  if (m.configError !== undefined && m.configError !== "") {
    return row(face, "bad", "дневной потолок задан неверно — ledger закрыт", m.configError);
  }
  if (!m.hasActivePrice) {
    return row(
      face,
      "bad",
      `нет действующей цены на ${m.provider}/${m.model} — ledger отклонит каждый вызов`,
      "модели «включены», но молча не работают: заведи цену в каталоге",
      at,
    );
  }
  if (m.openCircuits > 0) {
    return row(face, "bad", `провайдер отключён предохранителем (${m.openCircuits})`, undefined, at);
  }
  if (m.stuckCount > 0) {
    return row(face, "bad", `зависших резервов ${m.stuckCount} — исход вызова неизвестен`, undefined, at);
  }
  if (m.budgetCapUsd <= 0) {
    return row(face, "bad", "дневной потолок нулевой — ledger отклонит каждый вызов", undefined, at);
  }
  if (m.budgetRemainingUsd <= 0) {
    return row(face, "bad", "дневной потолок исчерпан — вызовы до полуночи отклоняются", undefined, at);
  }
  // Ни одного завершённого вызова: «отказов нет» здесь — та же ложь, что ноль
  // прогонов у монитора.
  //
  // ГАРД СПРАШИВАЕТ РАЗОБРАННЫЙ МОМЕНТ, А НЕ СЫРОЕ ПОЛЕ. Различие не
  // косметическое: `latestCompletedAt: "не дата"` мимо `=== null` проходит, а
  // `разобрать` его отбрасывает — и строка уходила в `ok` «вызовы проходят,
  // отказов сегодня 0» без единой отметки времени. Две формулировки, потому
  // что случаи разные: «вызовов не было» и «вызов был, а когда — не читается»
  // чинят в разных местах, и вторую нельзя называть первой.
  if (at === undefined) {
    return row(
      face,
      "unknown",
      m.latestCompletedAt === null
        ? "завершённых вызовов не было — оценивать нечего"
        : "момент последнего завершённого вызова не читается — оценивать нечем",
      m.latestCompletedAt === null
        ? undefined
        : `ledger вернул «${m.latestCompletedAt}» вместо даты: судить о свежести вызовов нечем`,
    );
  }
  // ПОСЛЕДНИЙ ЗАВЕРШЁННЫЙ ВЫЗОВ ОТКАЗАЛ — «вызовы проходят» сказать нельзя
  // (A-3). Утверждение строки касается не истории, а того, может ли система
  // позвать провайдера ПРЯМО СЕЙЧАС: успешных вызовов после этого отказа не
  // было, и это самое свежее, что о маршруте к модели известно. Голое число
  // отказов за день красным по-прежнему не красит (один 429 — не авария): там
  // рядом стоял УСПЕШНЫЙ последний вызов, здесь его нет.
  if (m.latestCompletedStatus === "failed") {
    const почему = m.latestCompletedOutcome !== null ? ` (${m.latestCompletedOutcome})` : "";
    return row(
      face,
      "bad",
      `последний завершённый вызов отказал${почему} — успешных после него не было`,
      `отказов сегодня ${m.failuresToday}; предохранитель провайдера при обычной ошибке не открывается, ` +
        "поэтому строка судит по исходу последнего вызова, а не по нему",
      at,
    );
  }
  return row(
    face,
    "ok",
    `вызовы проходят, отказов сегодня ${m.failuresToday}`,
    `остаток дневного потолка ${m.budgetRemainingUsd.toFixed(2)} из ${m.budgetCapUsd.toFixed(2)} USD`,
    at,
  );
}

/**
 * Источник не прочитался: строка честно говорит об этом, а не исчезает.
 *
 * Пропавшая строка читается как «такого источника нет», а `ok` по умолчанию —
 * как «всё хорошо». Оба варианта хуже, чем «оценить нечем».
 *
 * ТЕКСТ ИСКЛЮЧЕНИЯ СЮДА НЕ ПОПАДАЕТ (постановление ветки). Сообщения драйвера
 * несут хост и пользователя базы, а наружу едет НАШ ярлык прочитанного
 * («снимок расписаний»); причина отказа пишется только в журнал Core. Маршрут
 * с тех пор закрыт токеном (`ReadTokenGuard`, круг починок C-1), но ярлык
 * остаётся вторым поясом: держатель сервисного токена — это ещё и бот, и
 * агенты, и им строка подключения к базе Core ни к чему.
 *
 * ТРЕТИЙ АРГУМЕНТ ОБЯЗАТЕЛЬНЫЙ, А НЕ «`null` по умолчанию». Отказ чтения не
 * значит, что о проверках не известно ничего: отчёт OurVend может не собраться
 * при исправно прочитанном журнале прогонов — тик монитора известен, и «не
 * запускался» было бы ложью о работающем мониторе. Обязательный аргумент
 * заставляет вызывающего ответить, что он успел прочитать, а не забыть об этом
 * молча. Где не прочитался сам журнал проверок, момента нет — `null`, и это
 * единственное место, где `null` означает «не знаем», а не «не было»;
 * настоящий диагноз стоит первым словом в `summary`.
 */
export function unavailableRow(face: FaceMeta, источник: string, проверено: Date | null): HealthRow {
  return сПроверкой(
    row(
      face,
      "unknown",
      "источник не отвечает — оценить нечем",
      `не прочитано: ${источник}. Причина записана в журнал Core.`,
    ),
    проверено,
  );
}

/** Разделы по природе связи (Р-3): «снаружи» — только то, что ходит в чужую систему. */
export function splitSections(rows: readonly HealthRow[]): {
  outside: HealthRow[];
  internal: HealthRow[];
} {
  const outside: HealthRow[] = [];
  const internal: HealthRow[] = [];
  for (const r of rows) {
    if (OUTSIDE_KEYS.includes(r.key)) outside.push(r);
    else internal.push(r);
  }
  return { outside, internal };
}
