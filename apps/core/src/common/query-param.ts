/**
 * Чтение параметров строки запроса на границе контроллеров.
 *
 * Express отдаёт `?agent=a&agent=b` МАССИВОМ, а не строкой, и типы Nest этого
 * не показывают: параметр объявлен `string`, а приходит `string[]`. Без общего
 * места каждый контроллер вспоминает об этом сам — и `routines.controller.ts`
 * с `agents.controller.ts` вспоминали двумя копиями одного кода.
 */

/**
 * Первое значение параметра строки запроса; `undefined`, если параметра нет,
 * он пуст или пришёл не строкой.
 *
 * Массив (повторённый параметр) сводится к первому элементу: иначе фильтр
 * уехал бы в `eq(column, ["a","b"])` и вернул 500 от драйвера, а сравнение с
 * именем в витрине навыков не совпало бы никогда — панель получала бы пустую
 * деку вместо строк первого агента. Пустая строка — это «фильтр не задан»,
 * а не «фильтр по пустому имени»: `?agent=` фильтром не является.
 */
export function first(v: unknown): string | undefined {
  const raw = Array.isArray(v) ? v[0] : v;
  return typeof raw === "string" && raw.length > 0 ? raw : undefined;
}
