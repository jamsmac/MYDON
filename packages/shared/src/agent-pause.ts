/**
 * Тумблеры паузы парка агентов — ОДНО правило чтения на всю систему
 * (круг починок среза A2, C-6).
 *
 * `AGENTS_TASKS_PAUSED` и `AGENTS_SCHEDULES_PAUSED` читают три двери:
 * рантайм агентов (`apps/agents/src/polling.ts` — по нему агент решает,
 * работать ли), состояние агентов (`GET /agents/status` — по нему рисуется
 * сетка на главной) и доска рутин (`/routines/board`). До этой правки двери
 * разъехались на одном символе: рантайм сравнивал `raw?.trim() !== "0"`, а обе
 * стороны Core — `value !== "0"`. Значение `" 0 "` давало «пауза» на двух
 * экранах при РАБОТАЮЩИХ агентах — отказ в безопасную сторону, но экран,
 * противоречащий факту, и есть тот дефект, ради которого срез делался.
 *
 * Дом — `@mydon/shared`, потому что все три приложения уже от него зависят и
 * ничего лишнего это не тянет: модуль без импортов.
 */

/** Единственное значение, которое РАЗРЕШАЕТ работу. Всё прочее — пауза. */
export const AGENT_PAUSE_OFF = "0";

/**
 * Стоит ли соответствующий вид работы на паузе.
 *
 * FAIL-CLOSED: ключа нет, значение пустое, с пробелами или с опечаткой —
 * «на паузе». Дефолт обоих тумблеров в `config-spec` равен «1», и выключатель
 * всего парка обязан ломаться в «выключено»: пустой или чужой ответ настроек
 * не должен рисовать двенадцать работающих агентов там, где задачи стоят.
 */
export function agentWorkPaused(raw: string | null | undefined): boolean {
  return raw?.trim() !== AGENT_PAUSE_OFF;
}
