/**
 * Контракт снимка расписаний как heartbeat слоя агентов (перепроверка A2,
 * корень 2; ревью I-3).
 *
 * ОДНО ЧИСЛО НА ДВА ПРИЛОЖЕНИЯ — тот же приём, что у heartbeat бота
 * (`bot-heartbeat.ts`). Рантайм агентов переписывает снимок раз в период
 * (`apps/agents/src/index.ts`, тик перечитки настроек), а Core — доска рутин
 * и здоровье приложений — считает снимок протухшим через
 * `AGENTS_SNAPSHOT_MISS_LIMIT` периодов (`routines/board.ts`, `STALE_AFTER_SEC`).
 * Две копии числа разошлись бы молча: стоит рантайму начать писать реже, чем
 * ждёт Core, — и `/crons` с `/apps` объявляли бы слой мёртвым каждый цикл.
 */

/** Период записи снимка рантаймом агентов. */
export const AGENTS_SNAPSHOT_INTERVAL_MS = 10 * 60_000;

/**
 * Сколько периодов молчания Core прощает, прежде чем сказать «слой не отчитывался».
 *
 * Три — это ДВА пропущенных тика: рантайм не пишет снимок, когда Core
 * недоступен в момент тика (редеплой), а следующий тик ложится со своей
 * задержкой. Прежний порог 900 с при периоде 600 с прощал ноль тиков: один
 * редеплой Core, совпавший с тиком, давал пять минут «Слой агентов — сломано»
 * и восемь строк «не оценить» — ложную аварию при каждой выкатке.
 */
export const AGENTS_SNAPSHOT_MISS_LIMIT = 3;
