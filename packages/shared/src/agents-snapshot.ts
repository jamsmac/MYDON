/**
 * Контракт снимка расписаний как heartbeat слоя агентов (перепроверка A2,
 * корень 2; ревью I-3).
 *
 * ОДНО ЧИСЛО НА ДВА ПРИЛОЖЕНИЯ — тот же приём, что у heartbeat бота
 * (`bot-heartbeat.ts`). Рантайм агентов переписывает снимок раз в период
 * (`apps/agents/src/index.ts`, тик перечитки настроек), а Core — доска рутин
 * и здоровье приложений — считает снимок протухшим через
 * `AGENTS_SNAPSHOT_MISS_LIMIT` периодов (`routines/board.ts`, `STALE_AFTER_SEC`),
 * но не дольше `AGENTS_SNAPSHOT_MAX_SILENCE_SEC`.
 * Две копии числа разошлись бы молча: стоит рантайму начать писать реже, чем
 * ждёт Core, — и `/crons` с `/apps` объявляли бы слой мёртвым каждый цикл.
 */

/**
 * Период тика рантайма агентов: перечитка настроек и карточек из Core плюс
 * запись снимка. Он же — период heartbeat слоя.
 *
 * ПЯТЬ МИНУТ, А НЕ ДЕСЯТЬ (ревью Ф-4). Порог молчания равен
 * `интервал × MISS_LIMIT`, и на десятиминутном тике он давал полчаса: мёртвый
 * контейнер агентов держал `/apps` зелёным и `/crons` без чипа тридцать минут,
 * а occurrences материализует сам рантайм — до получаса молча пропущенных
 * срабатываний под спокойным экраном (`rollout_cleanup` оставляет
 * `mydon-agents` остановленным после сбоя за миграциями). Пять минут при том
 * же лимите дают прежние 15 минут детекта и вдвое быстрее применяют правки
 * карточек и тумблеров — то, что владельцу обещает панель.
 */
export const AGENTS_SNAPSHOT_INTERVAL_MS = 5 * 60_000;

/**
 * Сколько периодов молчания Core прощает, прежде чем сказать «слой не отчитывался».
 *
 * Три — это ДВА пропущенных тика: рантайм не пишет снимок, когда Core
 * недоступен в момент тика (редеплой), а следующий тик ложится со своей
 * задержкой. Прежний порог 900 с при периоде 600 с прощал ноль тиков: один
 * редеплой Core, совпавший с тиком, давал пять минут «Слой агентов — сломано»
 * и восемь строк «не оценить» — ложную аварию при каждой выкатке.
 */
export const AGENTS_SNAPSHOT_MISS_LIMIT = 3;

/**
 * Верхняя граница окна молчания, за которой «слой мёртв» узнают слишком поздно
 * (ревью Ф-4): occurrences материализует рантайм, и каждая минута тишины — это
 * молча пропущенные срабатывания под зелёным экраном. Пин на случай, если
 * кто-то поднимет интервал или лимит «чтобы не мигало».
 */
export const AGENTS_SNAPSHOT_MAX_SILENCE_SEC = 900;
