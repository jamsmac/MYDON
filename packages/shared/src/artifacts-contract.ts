/**
 * Договор кольца артефактов (срез A3): виды вложений и предел строки поиска.
 *
 * ПОЧЕМУ В ОБЩЕМ ПАКЕТЕ. Одни и те же значения ПИШЕТ бот
 * (`POST /attachments`), ПРОВЕРЯЕТ Core (`UploadDto.kind` и фильтр
 * `?kind=` витрины) и ПОКАЗЫВАЕТ панель (список в форме `/artifacts`) — тот
 * же довод, что у `MACHINE_KINDS` в `catalog-kinds.ts`. Разъехавшись, они
 * дают «принято при загрузке, но не находится фильтром» — и владелец видит
 * пустой архив вместо своего файла.
 *
 * До этого модуля список жил в ТРЁХ местах: inline-литерал в `@IsIn` у
 * `UploadDto`, `ARTIFACT_KINDS` в `artifacts.service.ts` и `ARTIFACT_KINDS`
 * в `apps/cc/src/lib/artifacts.ts`. Два теста заявляли сверку «с
 * `UploadDto.kind`», а сравнивали свой источник со СВОИМ ЖЕ литералом: до
 * inline-`@IsIn` не дотягивался никто, и четвёртый вид, добавленный в DTO,
 * не покраснил бы ничего (круг починок 3, B-1).
 *
 * ПОРЯДОК ЗДЕСЬ — ПОРЯДОК ХРАНЕНИЯ, А НЕ ПОКАЗА. У витрины свой
 * (документ первым: ради него срез и затевался), и он сверяется с этим
 * списком как ПЕРЕСТАНОВКА, а не буквально.
 */
export const ATTACHMENT_KINDS = ["photo", "receipt", "doc"] as const;
export type AttachmentKind = (typeof ATTACHMENT_KINDS)[number];

/**
 * Потолок строки поиска `?q=` у `GET /artifacts` — ОДИН на оба конца.
 *
 * Стоит `@MaxLength` у `ArtifactsQueryDto.q` в Core и `maxLength` у поля
 * формы в панели; панель тем же числом сужает значение из адреса ДО похода в
 * Core, потому что 400 на витрине раньше читался как «нет связи с ядром».
 * Пока число было записано в двух местах руками, «зеркало» держалось на
 * дисциплине автора: тест панели сверял его с собственным литералом.
 */
export const ARTIFACTS_Q_MAX = 200;
