/**
 * Контракт heartbeat Telegram-бота (волна A2, решение Р-5).
 *
 * ОДНО ЧИСЛО НА ДВА ПРИЛОЖЕНИЯ. Бот шлёт сигнал раз в этот период
 * (`apps/bot/src/heartbeat.ts`), Core решает по нему, жив ли поллер
 * (`apps/core/src/apps/apps-health.service.ts`), и ждёт сигнал не реже чем раз
 * в `BOT_HEARTBEAT_MISS_LIMIT` периодов. Две копии числа разъехались бы молча:
 * стоит боту начать слать реже, чем ждёт Core, — и панель показывала бы «бот
 * молчит» каждый цикл при живом боте. Поэтому число живёт здесь, а не по копии
 * в каждом приложении.
 */

/**
 * Период отправки heartbeat — он же шаг округления `clientKey`: два вызова в
 * одну и ту же пятиминутку обязаны схлопнуться в одну строку журнала.
 */
export const BOT_HEARTBEAT_INTERVAL_MS = 5 * 60_000;

/**
 * Сколько периодов молчания Core прощает, прежде чем сказать «бот молчит».
 *
 * Пять — это запас на рестарт контейнера и выкатку: одна пропущенная отправка
 * при деплое не должна красить строку, а двадцать пять минут тишины уже
 * означают, что поллер не работает.
 */
export const BOT_HEARTBEAT_MISS_LIMIT = 5;

/** Источник и тип события heartbeat: по ним Core ищет последний сигнал. */
export const BOT_HEARTBEAT_SOURCE = "bot";
export const BOT_HEARTBEAT_TYPE = "bot.heartbeat";
